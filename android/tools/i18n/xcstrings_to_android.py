#!/usr/bin/env python3
"""Copy the iOS app's translations into Android resources, so both apps say
the same words in all 38 locales.

    python3 android/tools/i18n/xcstrings_to_android.py [path/to/Localizable.xcstrings]

Input: android/tools/i18n/ios_strings.tsv, one `android_key<TAB>ios_key<TAB>target`
per line (target `main` = src/main/res, `direct` = src/direct/res, so a
direct-only string never reaches the Play APK's resources.arsc).

Output, idempotent (re-running rewrites only what it owns):
  * main: a delimited block inside values*/strings.xml, so
    tools/i18n/validate-translations.py checks placeholders, apostrophes,
    missing keys and untranslated values for these exactly like the rest;
  * main: values*/ios_strings.xml for what that validator cannot take:
    <plurals> (it reads <string> only), keys with no translation anywhere
    (translatable="false", English only) and keys whose translation equals
    the English in some locale (a loanword such as "Pro"; the validator's
    exception list lives outside android/, so they are kept apart instead);
  * direct: values*/ios_strings.xml in src/direct/res.

Format specifiers: %@ -> %N$s, %lld/%ld/%d -> %N$d, positional forms keep
their number. Plural variations become <plurals> with the same CLDR
quantities. Every value is checked here for placeholder agreement with the
English and for unescaped apostrophes before anything is written.
"""
import json
import pathlib
import re
import sys
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parents[3]
APP = ROOT / "android/gen/android/app/src"
TSV = pathlib.Path(__file__).with_name("ios_strings.tsv")
DEFAULT_CATALOG = ROOT.parent / "rostamvpn-ios/rostamvpn/Localizable.xcstrings"

# catalog locale -> Android values-* qualifiers
LOCALES = {
    "am": ["am"], "ar": ["ar"], "az": ["az"], "azb": ["b+azb"], "be": ["be"], "bo": ["bo"],
    "ckb": ["ckb"], "de": ["de"], "el": ["el"], "es": ["es"], "fa": ["fa", "fa-rIR"], "fi": ["fi"],
    "fr": ["fr"], "he": ["iw"], "hi": ["hi"], "hr": ["hr"], "id": ["in"], "it": ["it"], "kk": ["kk"],
    "km": ["km"], "ko": ["ko"], "ky": ["ky"], "my": ["my"], "nb": ["nb"], "nl": ["nl"], "pt": ["pt"],
    "ru": ["ru"], "sw": ["sw"], "tg": ["tg"], "th": ["th"], "ti": ["ti"], "tk": ["tk"], "tr": ["tr"],
    "uk": ["uk"], "uz": ["uz"], "vi": ["vi"], "zh-Hans": ["zh-rCN"],
}

# English singulars the catalog does not carry (its English is the key itself).
EN_PLURAL_ONE = {
    "%lld countries": "%lld country",
    "%lld days": "%lld day",
    "%lld days left": "%lld day left",
    "%lld min": "%lld min",
    "%lld texts": "%lld text",
}

BEGIN = "    <!-- BEGIN generated by android/tools/i18n/xcstrings_to_android.py from the iOS catalog. Do not edit by hand. -->"
END = "    <!-- END generated from the iOS catalog -->"

SPEC = re.compile(r"%(?:(\d+)\$)?(@|lld|ld|d|%)")


def convert(v: str) -> str:
    """iOS format string -> Android, numbering sequential arguments."""
    n = 0

    def rep(m):
        nonlocal n
        pos, kind = m.group(1), m.group(2)
        if kind == "%":
            return "%%"
        if pos is None:
            n += 1
            pos = str(n)
        return f"%{pos}${'s' if kind == '@' else 'd'}"
    return SPEC.sub(rep, v)


def android_escape(v: str) -> str:
    v = escape(v)                     # & < >
    v = v.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if v.startswith(("@", "?")):
        v = "\\" + v
    return v


def placeholders(v: str):
    return sorted(re.findall(r"%\d+\$[sd]", v))


def has_text(v: str) -> bool:
    return any(ch.isalpha() for ch in re.sub(r"%(?:\d+\$)?[sd]|%%", "", v))


def unit(loc_entry):
    su = (loc_entry or {}).get("stringUnit")
    return su.get("value") if su and su.get("value") else None


def plural(loc_entry):
    """CLDR forms of a plural entry, or None. Two catalog shapes: direct
    `variations.plural`, and a `%#@arg@` template whose `substitutions`
    carry the plural (Xcode writes that one when a translator pluralised a
    string the source left plain); `%arg` there stands for the argument."""
    e = loc_entry or {}
    p = e.get("variations", {}).get("plural")
    if p:
        return {q: x["stringUnit"]["value"] for q, x in p.items() if x.get("stringUnit", {}).get("value")}
    subs = e.get("substitutions")
    tmpl = unit(e)
    if subs and tmpl and len(subs) == 1:
        (name, sub), = subs.items()
        forms = sub.get("variations", {}).get("plural", {})
        spec = "%" + sub.get("formatSpecifier", "lld")
        return {q: tmpl.replace(f"%#@{name}@", x["stringUnit"]["value"].replace("%arg", spec))
                for q, x in forms.items() if x.get("stringUnit", {}).get("value")}
    return None


def main():
    catalog = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CATALOG
    cat = json.loads(catalog.read_text())["strings"]
    rows = []
    for line in TSV.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        a, i, t = line.split("\t")
        rows.append((a, i, t))

    errors = []
    # out[(target, file_kind)][qualifier] = list of xml lines
    out = {}

    def put(target, kind, qual, xml):
        out.setdefault((target, kind), {}).setdefault(qual, []).append(xml)

    for akey, ikey, target in rows:
        e = cat.get(ikey)
        if e is None:
            errors.append(f"{akey}: '{ikey}' is not in the catalog")
            continue
        locs = e.get("localizations", {})
        en_plural = plural(locs.get("en"))
        is_plural = en_plural is not None or any(plural(v) for k, v in locs.items() if k != "en")
        if is_plural:
            en = en_plural or {"one": EN_PLURAL_ONE.get(ikey, ikey), "other": ikey}
            en = {q: convert(v) for q, v in en.items()}
            want = placeholders(en["other"])
            put(target, "side", "", f'    <plurals name="{akey}">' + "".join(
                f'<item quantity="{q}">{android_escape(v)}</item>' for q, v in en.items()) + "</plurals>")
            for cl, quals in LOCALES.items():
                p = plural(locs.get(cl)) or ({"other": unit(locs.get(cl))} if unit(locs.get(cl)) else None)
                if not p:
                    errors.append(f"{akey}: no {cl} translation")
                    continue
                p = {q: convert(v) for q, v in p.items()}
                for q, v in p.items():
                    # "one day" / "two days" as words is correct CLDR usage
                    # (ar, he): those forms may drop the number, never add one.
                    ok = placeholders(v) == want or (q in ("zero", "one", "two") and not placeholders(v))
                    if not ok:
                        errors.append(f"{akey}/{cl}/{q}: placeholders {placeholders(v)} != en {want}")
                xml = f'    <plurals name="{akey}">' + "".join(
                    f'<item quantity="{q}">{android_escape(v)}</item>' for q, v in p.items()) + "</plurals>"
                for q in quals:
                    put(target, "side", q, xml)
            continue

        en = convert(unit(locs.get("en")) or ikey)
        want = placeholders(en)
        translated = {cl: unit(locs.get(cl)) for cl in LOCALES}
        if not any(translated.values()):
            # Nothing to translate (card brands, APN): English only, and the
            # framework never looks for a locale copy.
            put(target, "side", "", f'    <string name="{akey}" translatable="false">{android_escape(en)}</string>')
            continue
        missing = [cl for cl, v in translated.items() if not v]
        if missing:
            errors.append(f"{akey}: missing {missing}")
            continue
        conv = {cl: convert(v) for cl, v in translated.items()}
        for cl, v in conv.items():
            if placeholders(v) != want:
                errors.append(f"{akey}/{cl}: placeholders {placeholders(v)} != en {want}")
        same = [cl for cl, v in conv.items() if v == en and has_text(v)]
        kind = "side" if (same or target == "direct") else "block"
        put(target, kind, "", f'    <string name="{akey}">{android_escape(en)}</string>')
        for cl, v in conv.items():
            for q in LOCALES[cl]:
                put(target, kind, q, f'    <string name="{akey}">{android_escape(v)}</string>')
        if same and target == "main":
            print(f"  note: {akey} equals English in {same}; kept in ios_strings.xml")

    if errors:
        print("REFUSED, nothing written:")
        for e in errors:
            print("  -", e)
        return 1

    written = 0
    for (target, kind), by_qual in out.items():
        res = APP / target / "res"
        for qual, lines in by_qual.items():
            d = res / ("values" if not qual else f"values-{qual}")
            d.mkdir(parents=True, exist_ok=True)
            if kind == "side":
                body = "\n".join(lines)
                (d / "ios_strings.xml").write_text(
                    '<?xml version="1.0" encoding="utf-8"?>\n'
                    "<!-- GENERATED by android/tools/i18n/xcstrings_to_android.py from the iOS catalog. Do not edit by hand. -->\n"
                    f"<resources>\n{body}\n</resources>\n")
            else:
                f = d / "strings.xml"
                s = f.read_text()
                s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", "", s, flags=re.S)
                block = BEGIN + "\n" + "\n".join(lines) + "\n" + END + "\n"
                s = s.replace("</resources>", block + "</resources>", 1)
                f.write_text(s)
            written += 1
    # A locale whose side file lost every entry must not keep a stale one.
    for target in ("main", "direct"):
        for f in (APP / target / "res").glob("values*/ios_strings.xml"):
            qual = f.parent.name.replace("values", "").lstrip("-")
            if qual not in out.get((target, "side"), {}):
                f.unlink()
    print(f"{len(rows)} keys, {written} files written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
