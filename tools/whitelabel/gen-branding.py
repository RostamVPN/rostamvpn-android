"""Generate per-brand visual resources for BOTH platforms from the manifests.

    python3 tools/whitelabel/gen-branding.py            # all brands
    python3 tools/whitelabel/gen-branding.py rostam     # one brand
    python3 tools/whitelabel/gen-branding.py --check    # verify, write nothing

Two kinds of output, deliberately treated differently:

  TEXT (always generated)   app name, launcher background colour.
      Deterministic, tiny, and safe to overwrite. Generating it for EVERY brand
      is the point: today `rostam` declares neither and silently inherits the
      defaults in src/main, so a new brand that forgets to override ships
      calling itself RostamVPN. After this, main's copy is a fallback nothing
      relies on.

  IMAGES (only when a source exists)   launcher icons, iOS AppIcon set.
      Generated ONLY from brands/assets/<id>/icon.png. Without a source the
      existing hand-placed PNGs are left completely alone -- re-encoding 25
      shipped icons to prove a pipeline works would risk quality for no gain.
      New brands get the pipeline; existing brands keep their artwork until
      someone supplies a master file.

Requires `sips` (ships with macOS) for resizing; without it, image generation is
skipped and reported rather than silently producing nothing.
"""
from __future__ import annotations
import json
import pathlib
import shutil
import subprocess
import sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
BRANDS = ROOT / "brands"
ANDROID_SRC = ROOT / "android/gen/android/app/src"
ANDROID_DENSITIES = {
    "ldpi": 81, "mdpi": 108, "hdpi": 162,
    "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432,
}
LEGACY_DENSITIES = {d: round(px * 48 / 108) for d, px in ANDROID_DENSITIES.items()}
ADAPTIVE_CONTENT = 72 / 108
GEN_NOTE = "GENERATED by tools/whitelabel/gen-branding.py from brands/{src}. DO NOT EDIT."
DEFAULT_THEME = {
    "primary": "#3D6B6F", "primaryDeep": "#0E1E25", "secondary": "#4A9BA3",
    "accent": "#EFA638", "accentOnLight": "#DB4645", "success": "#45988A",
    "danger": "#E53935", "background": "#F5F5F5", "ink": "#2D3436",
    "warning": "#D7A23E",
}


def have_sips() -> bool:
    return shutil.which("sips") is not None


def write(path: pathlib.Path, body: str, check: bool, changed: list, unchanged: list) -> None:
    old = path.read_text() if path.exists() else None
    if old == body:
        unchanged.append(path)
        return
    changed.append(path)
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)


def xml_escape(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace('"', "&quot;").replace("'", "\\'"))


def gen_android_text(bid: str, m: dict, check: bool, changed: list, unchanged: list) -> None:
    b = m["branding"]
    name = xml_escape(b["appName"])
    tagline = xml_escape(b.get("tagline") or "")
    legal = m.get("legal") or {}
    operator = xml_escape(legal.get("operator") or b["appName"])
    email = xml_escape(legal.get("contactEmail") or "")
    site = xml_escape(legal.get("siteUrl") or "")
    res = ANDROID_SRC / bid / "res" / "values"
    write(res / "brand_strings.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
  <string name="app_name" translatable="false">{name}</string>
  <string name="main_activity_title" translatable="false">{name}</string>
  <string name="app_tagline">{tagline}</string>
  <string name="legal_operator" translatable="false">{operator}</string>
  <string name="legal_email" translatable="false">{email}</string>
  <string name="legal_site" translatable="false">{site}</string>
</resources>
""", check, changed, unchanged)
    write(res / "ic_launcher_background.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
  <color name="ic_launcher_background">{b['launcherBackground']}</color>
</resources>
""", check, changed, unchanged)
    gen_android_proof(bid, m, check, changed, unchanged)


def gen_android_proof(bid: str, m: dict, check: bool, changed: list, unchanged: list) -> None:
    """The paywall's trust row, per brand — store numbers, or nothing.

    These are FACTS ABOUT ONE LISTING, so they cannot live in the shared
    strings.xml: rostam has a million downloads and the other four do not, and a
    shared literal would make the paywall lie to four brands' users. Same reason
    The project rule bans `if (brand == ...)`; the answer is the same, a per-flavor
    resource fed by that brand's manifest.

    Absent (or 0) means the row is not drawn AT ALL — never a placeholder, never
    an invented number. A brand that has no audience yet simply does not make the
    claim, and gets it the day someone writes real numbers into its manifest.

    INTEGERS, not display strings, so the UI can format them with the device's
    own numbering system: the largest audience reads Persian, where "15,600"
    should render with Persian digits and separators. rating is in TENTHS for the
    same reason (a "4.1" literal would carry a Latin decimal point into every
    locale).

    Copy them from the brand's Play listing. Do not estimate.
    """
    p = m["branding"].get("proof") or {}
    res = ANDROID_SRC / bid / "res" / "values"
    write(res / "brand_proof.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
  <integer name="brand_proof_downloads">{int(p.get('downloads') or 0)}</integer>
  <integer name="brand_proof_rating_x10">{int(round(float(p.get('rating') or 0) * 10))}</integer>
  <integer name="brand_proof_reviews">{int(p.get('reviews') or 0)}</integer>
</resources>
""", check, changed, unchanged)


def gen_android_mascot(bid: str, m: dict, check: bool, changed: list, unchanged: list) -> None:
    """Does this brand have REAL mascot artwork? -> the connect button's face.

    The connect dial draws the brand's mascot where other brands draw a power
    glyph. That has to be a property of the BRAND, not a branch in Kotlin:
    The project rule bans `if (brand == ...)` because it makes every new brand a
    code change. Same answer as brand_proof -- a per-flavor resource fed by
    that brand's manifest.

    It is NOT inferred from whether src/<brand>/res/drawable/brand_mascot.png
    exists, because it always does: every brand ships one, and for four of the
    five it is a GENERATED PLACEHOLDER -- a brand-coloured disc with the first
    letter of the name. Those are not identical files (each carries its own
    colour and letter) but they are all placeholders, and putting one inside
    the dial would render a coloured disc inside a coloured disc with a letter
    on it. File existence cannot tell those apart from artwork; only the
    manifest can, so the manifest is asked.

    Absent means FALSE, and false means the power glyph -- which is correct for
    every brand and merely unbranded for one. The failure mode of forgetting to
    set it is a generic button, never a placeholder rendered as if it were a
    logo. A brand that commissions real artwork sets one flag and regenerates.
    """
    has = bool(m["branding"].get("hasMascot", False))
    scale = float(m["branding"].get("markScale", 1.0))
    disc_fills = bool(m["branding"].get("discFillsOnConnect", True))
    res = ANDROID_SRC / bid / "res" / "values"
    write(res / "brand_mascot.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
  <bool name="brand_has_mascot">{str(has).lower()}</bool>
  <item name="brand_mark_scale" type="dimen" format="float">{scale:.6f}</item>
  <bool name="brand_disc_fills_on_connect">{str(disc_fills).lower()}</bool>
</resources>
""", check, changed, unchanged)


def dark_ground(theme: dict) -> str:
    """The resting ground for a dark treatment, DERIVED from the brand.

    #101014 is a near-black with a whisper of blue, and 10% of the brand's own
    accent is mixed into it. A violet accent lands on a violet-black: Tor
    Browser's ground is an indigo-violet rather than a neutral grey, and the hue
    is what stops a dark app reading as "the OS dark theme" instead of as
    itself. 10% is enough to see next to a neutral grey and far too
    little to compete with the accent when it is spent on a control.

    Derived rather than authored so a sixth brand selecting a dark treatment gets
    its own ground with nothing to write, and so this file and Theme.kt cannot
    drift: the value is computed ONCE here and read from BrandPalette.
    """
    return mix("#101014", theme.get("accent") or theme["primary"], 0.10)


def light_ground(theme: dict) -> str:
    """The resting ground for a LIGHT treatment, derived the same way as
    `dark_ground` and for the same reason.

    The inverse move: 6% of the brand's own accent mixed into white. A violet
    accent lands on a violet-tinted paper.

    THIS IS WHAT MAKES A `rings` BRAND WORK IN LIGHT AT ALL. Its dial is a
    WHITE disc carrying a mark drawn for white, and on a white page that disc
    has 1.12:1 against its own background -- the hero of the dark screen simply
    dissolves. Tinting the PAGE instead of restyling the disc turns white back
    into figure, and the eye lands on the red rings and the mark. Trying to fix
    it from the disc side means a stroke or a knockout variant of an asset that
    has no dark-knockout variant, which is new artwork.

    6% was chosen by rendering 0.00 / 0.04 / 0.06 / 0.09 and looking: at 0.00
    the white card on the page is 1.01:1 and disappears, and at 0.09 the app
    reads as purple rather than red.
    """
    return mix("#FFFFFF", theme.get("accent") or theme["primary"], 0.06)


def dark_card(theme: dict) -> str:
    """One step lighter than the ground, which is what gives a dark screen depth
    without spending any colour. 7% white lands the card about 1.19:1 against
    its ground -- the SAME step the light scheme's card already uses
    against its page, so the two treatments have one rhythm rather than two."""
    return mix(dark_ground(theme), "#FFFFFF", 0.07)


def rgb(hexv: str) -> tuple:
    h = hexv.lstrip("#")
    if len(h) == 8:
        h = h[2:]
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a: str, b: str, t: float) -> str:
    ca, cb = rgb(a), rgb(b)
    return "#FF" + "".join(
        f"{round(ca[i] + (cb[i] - ca[i]) * t):02X}" for i in range(3))


def argb(hexv: str) -> str:
    h = hexv.lstrip("#").upper()
    return "#" + (h if len(h) == 8 else "FF" + h)


def gen_android_launch(bid: str, m: dict, check: bool, changed: list, unchanged: list) -> None:
    """The launch ground, in the brand's own colours, for both modes.

    Three colours, read by BOTH the splash theme and LaunchOverlay:

      launch_bg       the flat colour the system splash paints and the overlay
                      starts and ends on. It is the app's own background, so the
                      hand-off into the app has nothing to reveal.
      launch_bg_deep  the gradient's far stop, reached over the settle beat.
      launch_ink      the wordmark's colour (it ships as an alpha mask).

    They are generated rather than hand-placed because launch_bg has to equal
    BrandPalette.background exactly -- a hand-typed copy of it is precisely the
    drift that puts a flash back at the hand-off. `launchDeep` in the manifest
    overrides the derived light stop; rostam sets it to the iOS launch gradient's
    own parchment so the two platforms match rather than merely rhyme.

    Dark mode starts from #121212 (RostamDarkColorScheme.background, which is
    brand-neutral) and is overridden by `launchDeepNight`. The DERIVED dark stop
    is only a 20% pull toward primaryDeep, because primaryDeep is a brand hue and
    not a ground: a saturated red at the bottom of a dark splash is a warning
    light, not an identity.
    """
    t = m["branding"].get("theme") or DEFAULT_THEME
    res = ANDROID_SRC / bid / "res"
    bg = t["background"]
    bg_night = "#121212"
    deep = t.get("launchDeep") or mix(bg, t["primaryDeep"], 0.12)
    deep_night = t.get("launchDeepNight") or mix(bg_night, t["primaryDeep"], 0.20)
    write(res / "values/launch_colors.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
  <color name="launch_bg">{argb(bg)}</color>
  <color name="launch_bg_deep">{argb(deep)}</color>
  <color name="launch_ink">{argb(t['ink'])}</color>
  <color name="brand_ring">{argb(t.get('ring') or t['primary'])}</color>
  <item name="brand_ring_rest_alpha" type="dimen" format="float">{float(t.get('ringRestAlpha', 0.15)):.2f}</item>
</resources>
""", check, changed, unchanged)
    write(res / "values-night/launch_colors.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
  <color name="launch_bg">{argb(bg_night)}</color>
  <color name="launch_bg_deep">{argb(deep_night)}</color>
  <color name="launch_ink">{argb("#F0EDE6")}</color>
</resources>
""", check, changed, unchanged)


def gen_android_palette(bid: str, m: dict, check: bool, changed: list, unchanged: list) -> None:
    """Write the brand palette into the flavor's own source set.

    A Compose Color is a top-level val, not a resource lookup, so the palette
    cannot come from XML without touching every call site. Instead each flavor
    gets its OWN BrandPalette.kt and Color.kt reads from it: the 77 references to
    Brand1 keep working untouched, and switching brand switches the file.

    theme == null means the brand has no confirmed identity yet. It inherits the
    defaults rather than being handed invented colours, exactly like a null
    bundle id.
    """
    t = m["branding"].get("theme")
    out = ANDROID_SRC / bid / "java/com/rostamvpn/android/ui/theme" / "BrandPalette.kt"
    if not t:
        t = DEFAULT_THEME
        note = "No confirmed identity for this brand yet: these are the DEFAULTS."
    else:
        note = "Extracted from this brand's own shipped artwork. Not invented."
    def c(hexv):
        h = hexv.lstrip("#")
        if len(h) == 6:
            h = "FF" + h
        return "Color(0x" + h.upper() + ")"
    lines = [
        "// Copyright 2026 Internet Mastering & Company, Inc.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "package com.rostamvpn.android.ui.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "/**",
        " * The brand palette. One file per flavor; Color.kt reads from here.",
        " * " + GEN_NOTE.format(src=bid + ".json") + " " + note,
        " */",
        "object BrandPalette {",
    ]
    for k in ("primary", "primaryDeep", "secondary", "accent", "accentOnLight",
              "success", "danger", "warning", "background", "ink"):
        lines.append("    val " + k + " = " + c(t[k]))
    lines += ["}", ""]
    write(out, "\n".join(lines), check, changed, unchanged)


def inset_foreground(src: pathlib.Path, dst: pathlib.Path, canvas: int, scale: float) -> bool:
    """Draw `src` centred at `scale` of a transparent `canvas`x`canvas` square.

    Returns False (writing nothing) when Pillow is missing, so the caller can
    fall back rather than produce an empty file. sips cannot do this: it resizes
    and it pads, but `--padColor` is opaque, and an opaque pad would replace the
    adaptive icon's background layer with a coloured square.

    The source is measured by its ALPHA BOUNDING BOX, not its canvas: masters
    arrive with wildly different amounts of built-in padding (one master is
    edge-to-edge, another carries a transparent margin), and scaling the canvas
    would make `scale` mean something different for each brand.
    """
    try:
        from PIL import Image
    except ImportError:
        return False
    im = Image.open(src).convert("RGBA")
    bb = im.getchannel("A").getbbox() or (0, 0, *im.size)
    art = im.crop(bb)
    target = max(1, int(round(canvas * scale)))
    w, h = art.size
    ratio = target / max(w, h)
    art = art.resize((max(1, round(w * ratio)), max(1, round(h * ratio))), Image.LANCZOS)
    out = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    out.paste(art, ((canvas - art.width) // 2, (canvas - art.height) // 2), art)
    dst.parent.mkdir(parents=True, exist_ok=True)
    out.save(dst, "PNG", optimize=True)
    shrink(dst)
    return True


def shrink(path: pathlib.Path) -> None:
    """Palette-quantise a launcher PNG when that is meaningfully smaller.

    A gradient-heavy master (a coin, say) costs 146 KB at xxxhdpi as
    truecolour and 27 KB at 256 colours -- indistinguishable at 432px and utterly
    so at the 48-108dp it is actually drawn at, but 3 MB across a full icon set.
    This app is installed over metered mobile in Iran and the APK was just cut
    from 26 MB to 12 MB; a launcher icon must not give that back.

    Flat artwork (a flat shield, say) is already near the palette limit, so the
    result is kept only when it actually wins -- never at equal size, which would
    trade colour depth for nothing.
    """
    try:
        from PIL import Image
    except ImportError:
        return
    before = path.stat().st_size
    im = Image.open(path).convert("RGBA")
    q = im.quantize(colors=256, method=Image.FASTOCTREE)
    tmp = path.with_suffix(".png.tmp")
    q.save(tmp, "PNG", optimize=True)
    if tmp.stat().st_size < before:
        tmp.replace(path)
    else:
        tmp.unlink()


def gen_icons(bid: str, m: dict, check: bool, made: list, skipped: list) -> None:
    src_dir = ROOT / m["branding"]["assetsDir"]
    icon = src_dir / "icon.png"
    if not icon.exists():
        skipped.append(f"{bid}: no {icon.relative_to(ROOT)} -- existing artwork left untouched")
        return
    if not have_sips():
        skipped.append(f"{bid}: sips unavailable, cannot resize")
        return
    if check:
        made.append(f"{bid}: would generate {len(ANDROID_DENSITIES)} densities")
        return
    scale = float(m["branding"].get("adaptiveContentScale", ADAPTIVE_CONTENT))
    for dens, px in ANDROID_DENSITIES.items():
        out = ANDROID_SRC / bid / "res" / f"mipmap-{dens}"
        out.mkdir(parents=True, exist_ok=True)
        for name in ("ic_launcher.png",):
            subprocess.run(["sips", "-Z", str(LEGACY_DENSITIES[dens]), str(icon),
                            "--out", str(out / name)], capture_output=True, check=False)
            shrink(out / name)
        fg = out / "ic_launcher_foreground.png"
        if not inset_foreground(icon, fg, px, scale):
            subprocess.run(["sips", "-Z", str(px), str(icon), "--out", str(fg)],
                           capture_output=True, check=False)
            skipped.append(f"{bid}: Pillow unavailable -- ic_launcher_foreground written "
                           f"FULL-BLEED, so the adaptive mask will crop its outer "
                           f"{(1 - scale) * 100:.0f}%. pip install Pillow and re-run.")
    made.append(f"{bid}: {len(ANDROID_DENSITIES)} Android densities")


def main() -> int:
    check = "--check" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    manifests = {f.stem: json.loads(f.read_text())
                 for f in sorted(BRANDS.glob("*.json")) if f.name != "LOCKED.json"}
    wanted = args or sorted(manifests)
    changed: list = []
    unchanged: list = []
    made: list = []
    skipped: list = []
    for bid in wanted:
        m = manifests.get(bid)
        if m is None:
            print(f"  ERROR unknown brand {bid!r}", file=sys.stderr)
            return 2
        if "branding" not in m:
            print(f"  ERROR {bid}: manifest has no 'branding' block", file=sys.stderr)
            return 2
        gen_android_text(bid, m, check, changed, unchanged)
        gen_android_launch(bid, m, check, changed, unchanged)
        gen_android_palette(bid, m, check, changed, unchanged)
        gen_android_mascot(bid, m, check, changed, unchanged)
        gen_icons(bid, m, check, made, skipped)
    verb = "would write" if check else "wrote"
    for p in changed:
        print(f"  {verb} {p.relative_to(ROOT)}")
    if unchanged:
        print(f"  {len(unchanged)} file(s) already current")
    for s in made:
        print(f"  icons {s}")
    for s in skipped:
        print(f"  skip  {s}")
    if check and changed:
        print("\n  --check: resources are STALE, run without --check")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
