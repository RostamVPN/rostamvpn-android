def dark_ground(theme: dict) -> str:
    """The resting ground for a dark treatment, DERIVED from the brand.

    #101014 is a near-black with a whisper of blue, and 10% of the brand's own
    accent is mixed into it. For RedVPN (#69108C) that lands on #191020, a
    violet-black: Tor Browser's ground is an indigo-violet rather than a neutral
    grey, and the hue is what stops a dark app reading as "the OS dark theme"
    instead of as itself. 10% is enough to see next to a neutral grey and far too
    little to compete with the accent when it is spent on a control.

    Derived rather than authored so a sixth brand selecting a dark treatment gets
    its own ground with nothing to write, and so this file and Theme.kt cannot
    drift: the value is computed ONCE here and read from BrandPalette.
    """
    return mix("#101014", theme.get("accent") or theme["primary"], 0.10)


def light_ground(theme: dict) -> str:
    """The resting ground for a LIGHT treatment, derived the same way as
    `dark_ground` and for the same reason.

    The inverse move: 6% of the brand's own accent mixed into white. RedVPN
    (#69108C) lands on #F6F1F8, a violet-tinted paper.

    🚨 THIS IS WHAT MAKES A `rings` BRAND WORK IN LIGHT AT ALL. Its dial is a
    WHITE disc carrying a mark drawn for white, and on a white page that disc
    has 1.12:1 against its own background -- the hero of the dark screen simply
    dissolves. Tinting the PAGE instead of restyling the disc turns white back
    into figure, and the eye lands on the red rings and the mark. Trying to fix
    it from the disc side means a stroke or a knockout variant of an asset that
    has no dark-knockout variant, which is new artwork.

    6% was chosen by rendering 0.00 / 0.04 / 0.06 / 0.09 and looking: at 0.00
    the white card on the page is 1.01:1 and disappears (which is exactly what
    Android's RingsLightColorScheme ships today), and at 0.09 the app reads as
    purple rather than red.
    """
    return mix("#FFFFFF", theme.get("accent") or theme["primary"], 0.06)


def dark_card(theme: dict) -> str:
    """One step lighter than the ground, which is what gives a dark screen depth
    without spending any colour. 7% white lands RedVPN's card on #292130, 1.19:1
    against its ground -- the SAME step the light scheme's card already uses
    against its page, so the two treatments have one rhythm rather than two."""
    return mix(dark_ground(theme), "#FFFFFF", 0.07)


# The compositions that exist. Adding one means adding a Composable in
# ui/screens/home/ AND a branch in HomeStyle.from(); this set is the contract
# between the manifest and the Kotlin, so a manifest can never name a layout
# that has no renderer.
BRAND_STYLES = {"classic", "rings", "value", "tabs"}


def rgb(hexv: str) -> tuple:
    h = hexv.lstrip("#")
    if len(h) == 8:  # AARRGGBB
        h = h[2:]
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a: str, b: str, t: float) -> str:
    ca, cb = rgb(a), rgb(b)
    return "#FF" + "".join(
        f"{round(ca[i] + (cb[i] - ca[i]) * t):02X}" for i in range(3))


def argb(hexv: str) -> str:
    h = hexv.lstrip("#").upper()
    return "#" + (h if len(h) == 8 else "FF" + h)


def gen_android_launch(bid: str, m: dict, check: bool, changed: list, unchanged: list) -> None:
    """The launch ground, in the brand's own colours, for both modes.

    Three colours, read by BOTH the splash theme and LaunchOverlay:

      launch_bg       the flat colour the system splash paints and the overlay
                      starts and ends on. It is the app's own background, so the
                      hand-off into the app has nothing to reveal.
      launch_bg_deep  the gradient's far stop, reached over the settle beat.
      launch_ink      the wordmark's colour (it ships as an alpha mask).

    They are generated rather than hand-placed because launch_bg has to equal
    BrandPalette.background exactly -- a hand-typed copy of it is precisely the
    drift that puts a flash back at the hand-off. `launchDeep` in the manifest
    overrides the derived light stop; rostam sets it to the iOS launch gradient's
    own parchment so the two platforms match rather than merely rhyme.

    Dark mode starts from #121212 (RostamDarkColorScheme.background, which is
    brand-neutral) and is overridden by `launchDeepNight`. The DERIVED dark stop
    is only a 20% pull toward primaryDeep, because primaryDeep is a brand hue and
    not a ground: redvpn's is #BD0000, and a saturated red at the bottom of a
    dark splash is a warning light, not an identity.
    """
    t = m["branding"].get("theme") or DEFAULT_THEME
    res = ANDROID_SRC / bid / "res"
    # A DARK treatment's launch is dark in BOTH resource sets, because the app
    # itself is dark in both. Getting this wrong is a white flash before the
    # first frame, which is the one launch defect a user cannot miss.
    style = str(m["branding"].get("style", "classic")).strip().lower()
    is_dark = style in DARK_STYLES
    bg = dark_ground(t) if is_dark else t["background"]
    if style == "tabs":
        # Dark-first: the app paints dark unless the user picks Light, so the
        # system splash is the design's dark ground in both modes, or it
        # flashes light before the first frame.
        bg = bg_tabs_night = m["branding"]["themeDark"]["bg"]
    bg_night = dark_ground(t) if is_dark else "#121212"
    if style == "tabs":
        bg_night = bg_tabs_night
    ink_day = "#F4F1F6" if (is_dark or style == "tabs") else t["ink"]
    deep = t.get("launchDeep") or mix(bg, t["primaryDeep"], 0.12 if not is_dark else 0.28)
    deep_night = t.get("launchDeepNight") or mix(bg_night, t["primaryDeep"], 0.20 if not is_dark else 0.28)
    write(res / "values/launch_colors.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GEN_NOTE.format(src=bid + '.json')} -->
<resources>
  <color name="launch_bg">{argb(bg)}</color>
  <color name="launch_bg_deep">{argb(deep)}</color>
  <color name="launch_ink">{argb(ink_day)}</color>
  <!-- The connect ring. Defaults to primary; a brand whose MARK is a strong
       colour can point it elsewhere (DollarVPN's gold coin) so the ring and
       the mark belong to each other. PowerButton still runs it through
       legibleOn() against the background, so a ring that fails 3:1 falls back
       to the neutral rather than shipping unreadable. -->
  <color name="brand_ring">{argb(t.get('ring') or t['primary'])}</color>
  <!-- Opacity of the ring's socket track at rest. 0.15 suits a mid-dark hue on
       a light ground; a light or desaturated ring needs more or it vanishes. -->
  <item name="brand_ring_rest_alpha" type="dimen" format="float">{float(t.get('ringRestAlpha', 0.15)):.2f}</item>
  <!-- The concentric BAND stack of the `rings` home style. Defaults to
       accentOnLight, then primary: a band stack is drawn at four opacities
       down to 0.40, so it wants the palette's DEEP tone rather than its
       bright one. RedVPN's measured stack is accentOnLight (#BB0008, 6.57:1
       on white) while its primary (#E2232B, 4.54:1) is the wordmark's red. A
       brand whose palette carries no accentOnLight gets primary and a
       correct, if less contrasty, stack. Unused by the classic style. -->
  <color name="brand_band">{argb(t.get('band') or t.get('accentOnLight') or t['primary'])}</color>
</resources>
""", check, changed, unchanged)
    write(res / "values-night/launch_colors.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {GEN_NOTE.format(src=bid + '.json')} -->
<resources>
  <color name="launch_bg">{argb(bg_night)}</color>
  <color name="launch_bg_deep">{argb(deep_night)}</color>
  <color name="launch_ink">{argb("#F0EDE6" if not is_dark else ink_day)}</color>
</resources>
""", check, changed, unchanged)


def gen_android_palette(bid: str, m: dict, check: bool, changed: list, unchanged: list) -> None:
    """Write the brand palette into the flavor's own source set.

    A Compose Color is a top-level val, not a resource lookup, so the palette
    cannot come from XML without touching every call site. Instead each flavor
    gets its OWN BrandPalette.kt and Color.kt reads from it: the 77 references to
    Brand1 keep working untouched, and switching brand switches the file.

    theme == null means the brand has no confirmed identity yet. It inherits the
    defaults rather than being handed invented colours, exactly like a null
    bundle id.
    """
    t = m["branding"].get("theme")
    out = ANDROID_SRC / bid / "java/com/rostamvpn/android/ui/theme" / "BrandPalette.kt"
    if not t:
        # Emit defaults so EVERY flavor has the symbol. A missing file would fail
        # only that flavor, at compile time, with a confusing unresolved-reference.
        t = DEFAULT_THEME
        note = "No confirmed identity for this brand yet: these are the DEFAULTS."
    else:
        note = "Extracted from this brand's own shipped artwork. Not invented."

    def c(hexv):
        h = hexv.lstrip("#")
        if len(h) == 6:
            h = "FF" + h
        return "Color(0x" + h.upper() + ")"

    lines = [
        "// " + GEN_NOTE.format(src=bid + ".json"),
        "//",
        "// " + note,
        "package com.rostamvpn.android.ui.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "/** The brand palette. One file per flavor; Color.kt reads from here. */",
        "object BrandPalette {",
    ]
    for k in ("primary", "primaryDeep", "secondary", "accent", "accentOnLight",
              "success", "danger", "warning", "background", "ink"):
        lines.append("    val " + k + " = " + c(t[k]))
    # Derived, and emitted for EVERY brand so the value has one source. A brand
    # on a light treatment simply never reads them.
    lines.append("")
    lines.append("    /** Resting ground for a dark treatment. See gen-branding.dark_ground. */")
    lines.append("    val groundDark = " + c(dark_ground(t)))
    lines.append("    /** One step lighter: the card fill on that ground. */")
    lines.append("    val cardDark = " + c(dark_card(t)))
    lines += ["}", ""]
    # The `tabs` treatment's own token sets (branding.themeDark / themeLight).
    # Emitted for EVERY brand so the shared Kotlin compiles in every flavor; a
    # brand on another style never reads them. A `tabs` brand without them is
    # rejected in gen_android_layout, so these defaults never render.
    td = m["branding"].get("themeDark") or TABS_DEFAULT_DARK
    tl = m["branding"].get("themeLight") or TABS_DEFAULT_LIGHT
    for name, tok in (("TabsDark", td), ("TabsLight", tl)):
        lines.append("/** `tabs` treatment tokens. See branding.themeDark/themeLight. */")
        lines.append("object " + name + " {")
        for k in TABS_TOKENS:
            lines.append("    val " + k + " = " + c(tok[k]))
        lines += ["}", ""]
    write(out, "\n".join(lines), check, changed, unchanged)


def inset_foreground(src: pathlib.Path, dst: pathlib.Path, canvas: int, scale: float) -> bool:
    """Draw `src` centred at `scale` of a transparent `canvas`x`canvas` square.

    Returns False (writing nothing) when Pillow is missing, so the caller can
    fall back rather than produce an empty file. sips cannot do this: it resizes
    and it pads, but `--padColor` is opaque, and an opaque pad would replace the
    adaptive icon's background layer with a coloured square.

    The source is measured by its ALPHA BOUNDING BOX, not its canvas: masters
    arrive with wildly different amounts of built-in padding (the RedVPN master
    is edge-to-edge, a coin master carries a transparent margin), and scaling the
    canvas would make `scale` mean something different for each brand.
    """
    try:
        from PIL import Image
    except ImportError:
        return False
    im = Image.open(src).convert("RGBA")
    bb = im.getchannel("A").getbbox() or (0, 0, *im.size)
    art = im.crop(bb)
    target = max(1, int(round(canvas * scale)))
    w, h = art.size
    ratio = target / max(w, h)
    art = art.resize((max(1, round(w * ratio)), max(1, round(h * ratio))), Image.LANCZOS)
    out = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    out.paste(art, ((canvas - art.width) // 2, (canvas - art.height) // 2), art)
    dst.parent.mkdir(parents=True, exist_ok=True)
    out.save(dst, "PNG", optimize=True)
    shrink(dst)
    return True


def shrink(path: pathlib.Path) -> None:
    """Palette-quantise a launcher PNG when that is meaningfully smaller.

    A gradient-heavy master (the DollarVPN coin) costs 146 KB at xxxhdpi as
    truecolour and 27 KB at 256 colours -- indistinguishable at 432px and utterly
    so at the 48-108dp it is actually drawn at, but 3 MB across a full icon set.
    This app is installed over metered mobile in Iran and the APK was just cut
    from 26 MB to 12 MB; a launcher icon must not give that back.

    Flat artwork (the RedVPN shield) is already near the palette limit, so the
    result is kept only when it actually wins -- never at equal size, which would
    trade colour depth for nothing.
    """
    try:
        from PIL import Image
    except ImportError:
        return
    before = path.stat().st_size
    im = Image.open(path).convert("RGBA")
    q = im.quantize(colors=256, method=Image.FASTOCTREE)
    tmp = path.with_suffix(".png.tmp")
    q.save(tmp, "PNG", optimize=True)
    if tmp.stat().st_size < before:
        tmp.replace(path)
    else:
        tmp.unlink()


def gen_icons(bid: str, m: dict, check: bool, made: list, skipped: list) -> None:
    src_dir = ROOT / m["branding"]["assetsDir"]
    icon = src_dir / "icon.png"
    if not icon.exists():
        skipped.append(f"{bid}: no {icon.relative_to(ROOT)} -- existing artwork left untouched")
        return
    if not have_sips():
        skipped.append(f"{bid}: sips unavailable, cannot resize")
        return
    if check:
        made.append(f"{bid}: would generate {len(ANDROID_DENSITIES)} densities")
        return

    scale = float(m["branding"].get("adaptiveContentScale", ADAPTIVE_CONTENT))

    for dens, px in ANDROID_DENSITIES.items():
        out = ANDROID_SRC / bid / "res" / f"mipmap-{dens}"
        out.mkdir(parents=True, exist_ok=True)
        # Pre-API-26 icons are full-bleed at the 48dp sizes; nothing masks them.
        for name in ("ic_launcher.png", "ic_launcher_round.png"):
            subprocess.run(["sips", "-Z", str(LEGACY_DENSITIES[dens]), str(icon),
                            "--out", str(out / name)], capture_output=True, check=False)
            shrink(out / name)
        fg = out / "ic_launcher_foreground.png"
        if not inset_foreground(icon, fg, px, scale):
            # No compositing available: full-bleed is wrong but recoverable, and
            # silently writing nothing would be worse. Say so, loudly, once.
            subprocess.run(["sips", "-Z", str(px), str(icon), "--out", str(fg)],
                           capture_output=True, check=False)
            skipped.append(f"{bid}: Pillow unavailable -- ic_launcher_foreground written "
                           f"FULL-BLEED, so the adaptive mask will crop its outer "
                           f"{(1 - scale) * 100:.0f}%. pip install Pillow and re-run.")
    # iOS icons are NOT written here any more. They belong to gen-ios.py, which
    # writes into the iOS REPO -- `ios/generated/` in this repo was a copy
    # nothing consumed, so it went stale silently (redvpn's icon-1024.png was
    # frozen from before a rename and nobody was told). gen-ios.py also reads
    # `ios-icon.png` in preference to `icon.png`, so a brand can have an iOS
    # master WITHOUT triggering the Android regeneration below, which would
    # destroy hand-tuned per-density art.
    made.append(f"{bid}: {len(ANDROID_DENSITIES)} Android densities")


def main() -> int:
    check = "--check" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    manifests = {f.stem: json.loads(f.read_text())
                 for f in sorted(BRANDS.glob("*.json")) if f.name != "LOCKED.json"}
    wanted = args or sorted(manifests)

    changed: list = []
    unchanged: list = []
    made: list = []
    skipped: list = []
    for bid in wanted:
        m = manifests.get(bid)
        if m is None:
            print(f"  ERROR unknown brand {bid!r}", file=sys.stderr)
            return 2
        if "branding" not in m:
            print(f"  ERROR {bid}: manifest has no 'branding' block", file=sys.stderr)
            return 2
        gen_android_text(bid, m, check, changed, unchanged)
        gen_android_launch(bid, m, check, changed, unchanged)
        gen_android_palette(bid, m, check, changed, unchanged)
        gen_android_mascot(bid, m, check, changed, unchanged)
        gen_android_layout(bid, m, check, changed, unchanged)
        gen_icons(bid, m, check, made, skipped)

    verb = "would write" if check else "wrote"
    for p in changed:
        print(f"  {verb} {p.relative_to(ROOT)}")
    if unchanged:
        print(f"  {len(unchanged)} file(s) already current")
    for s in made:
        print(f"  icons {s}")
    for s in skipped:
        print(f"  skip  {s}")
    if check and changed:
        print("\n  --check: resources are STALE, run without --check")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
