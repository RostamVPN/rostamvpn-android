#!/usr/bin/env python3
"""Generate the iOS per-brand build inputs from the SAME manifests Android uses.

    python3 tools/whitelabel/gen-ios.py --ios-repo ~/silo/rostamvpn-ios
    python3 tools/whitelabel/gen-ios.py --ios-repo ~/silo/rostamvpn-ios rostam redvpn
    python3 tools/whitelabel/gen-ios.py --ios-repo ~/silo/rostamvpn-ios --check

Emits, per brand, INTO THE iOS REPO at `Brands/<brand>/`:

    Brand.xcconfig      every BRAND_* build setting -- identity, version, team
    BrandTheme.swift    colours, the exact mirror of Android's BrandPalette.kt
    Brand.xcassets/     AppIcon, when a 1024 master exists to build it from

Those files are COMMITTED in the iOS repo. `Scripts/select-brand.sh <brand>`
then copies them into the GITIGNORED working locations (`Config/Brand.xcconfig`
and `rostamvpn/Brand/`), which is what the Xcode project actually reads.

WHY IT WRITES INTO THE OTHER REPO
---------------------------------
It used to write `ios/generated/<brand>/` HERE and nothing copied it across.
`rostamvpn/Brand.swift` in the iOS repo was byte-identical to the generated
`rostam/Brand.swift` because someone copied it once, by hand; the `Brand.xcconfig`
sibling was never copied at all. That is how the paywall shipped with an empty
product list: `storeKitProductIDs` was updated here and the app was still built
with `[]`. One copy of a generated file, in the place that consumes it.

`Brand.swift` IS NO LONGER GENERATED. Identity now travels
xcconfig -> Info.plist -> `BrandRuntime` (in RostamKit), because there are three
compile units -- the app, the Network Extension and the SPM package -- and no
app-target Swift file is visible to the other two. The only generated Swift left
is `BrandTheme.swift`, colours, which only the app draws.

FAIL CLOSED
-----------
A wrong brand value fails SILENTLY on iOS: an unregistered bundle id, a build
number already used, a product id that does not exist. So a missing or
inconsistent manifest field is a hard error with NO output, never a guess.
"""
