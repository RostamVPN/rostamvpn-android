class BrandError(Exception):
    pass


def bundled_config_src(bid: str, m: dict) -> pathlib.Path | None:
    """The config this brand bundles as its BOOT config, or None.

    OPT-IN via `ios.bundleConfig`, and the opt-in is the whole design. iOS has
    never bundled a config at ALL -- `RedSocketTunnel/default-config.json` has
    zero pbxproj references, both Resources phases are empty, and no built .app
    contains any JSON -- so before its first successful fetch every brand runs
    `ConfigPolicy.Snapshot.fallback`: ads OFF, throttle OFF, freedom tier ON.

    That means handing a LIVE brand a boot config is a behaviour change, not a
    no-op: rostam's own config carries ads.enabled true and throttle 2000, which
    would become true at first launch where today they are false. rostam and
    redvpn therefore do not opt in and keep `Snapshot.fallback` exactly.

    DollarVPN opts in because its policy is the OPPOSITE of the fallback in the
    two places the first screen talks about (`freedom_tier` false, `hard_stop`
    true), and because the config that would correct it arrives from the SHARED
    remote slot, which carries rostam's answer (CLAUDE.md 8).
    """
    if not (m.get("ios") or {}).get("bundleConfig"):
        return None
    src = CONFIGS / f"{bid}.json"
    if not src.is_file():
        raise BrandError(
            f"ios.bundleConfig is true but {src.relative_to(ROOT)} does not exist. "
            f"The bundled config is COPIED from that file, never written here, so that "
            f"iOS and Android cannot hold different policy for one brand -- Android "
            f"overlays the same bytes as src/{bid}/assets/default-config.json."
        )
    return src


def assert_icon_opaque(path):
    """App Store icons may not have an alpha channel. Fail here, not at upload.

    ITMS-90717 rejects a transparent icon at the very last step, after a full
    archive and upload, and iOS composites the transparent regions on black on
    the home screen. `sips -Z` preserves alpha, so copying a source icon is not
    enough. DollarVPN shipped a genuinely transparent RGBA icon this way and
    nothing caught it: the size guard checks size, and the brand verifier only
    checks that an AppIcon exists.
    """
    try:
        from PIL import Image
    except ImportError:
        return  # no Pillow, no check; better than crashing the generator
    im = Image.open(path)
    if im.mode in ("RGBA", "LA") and im.getextrema()[-1][0] < 255:
        raise SystemExit(
            f"{path}: App Store icon has real transparency and would be "
            f"rejected as ITMS-90717. Composite it on the brand background first."
        )

def xc(value: str) -> str:
    """Escape a value for an xcconfig.

    ⚠️ An xcconfig strips everything after `//` as a COMMENT and has no escape,
    so `https://cashier.example.com` written literally becomes `https:`. That shipped
    once and was caught only by diffing the built Info.plist against a baseline.
    `$()` expands to the empty string, which separates the two slashes in the
    source text without changing the value. Scripts/verify-brand.sh in the iOS
    repo also asserts the URL keys still look like URLs after substitution.
    """
    return value.replace("//", "/$()/")


def check(m: dict, bid: str) -> dict:
    """Hard-fail on anything that would ship a silently wrong iOS build."""
    ios = m.get("ios") or {}
    locked = (LOCKED.get(bid) or {}).get("ios") or {}

    def need(key):
        v = ios.get(key)
        if v in (None, "", []):
            raise BrandError(f"ios.{key} is missing; it cannot be guessed")
        return v

    bundle = need("bundleId")
    tunnel = need("tunnelBundleId")
    need("teamId")
    need("marketingVersion")
    if ios.get("buildNumber") in (None, ""):
        raise BrandError(
            "ios.buildNumber is missing. Read it from App Store Connect "
            "(GET /v1/builds?filter[app]=<appStoreId>&sort=-uploadedDate) and record "
            "how you read it. An expired build still burns its number, and a number "
            "already used is rejected at the last step of an upload."
        )

    for key, want in (("bundleId", locked.get("bundleId")),
                      ("tunnelBundleId", locked.get("tunnelBundleId")),
                      ("teamId", locked.get("teamId"))):
        if want and ios.get(key) != want:
            raise BrandError(f"ios.{key} is {ios.get(key)!r} but LOCKED.json says {want!r}. "
                             f"These identifiers are PERMANENT; fix the manifest, not LOCKED.json.")

    if not tunnel.startswith(bundle + "."):
        raise BrandError(f"ios.tunnelBundleId {tunnel!r} is not prefixed by ios.bundleId {bundle!r}. "
                         f"iOS refuses to load an app extension that is not under its container app.")
    if tunnel.endswith(".tunnel") and bid == "rostam":
        raise BrandError("rostam's tunnel id must stay .redsocket; renaming a live app's "
                         "provider id orphans every saved NEVPNManager profile on every device.")
    if tunnel in (ios.get("legacyTunnelBundleIds") or []):
        raise BrandError(
            f"ios.tunnelBundleId {tunnel!r} is ALSO in ios.legacyTunnelBundleIds. "
            f"TunnelProfile.removeStaleProfiles() deletes every profile in that list at "
            f"launch, so the app would delete its own VPN profile on every launch and tear "
            f"down a live tunnel. This happens when tunnelBundleId is changed and the legacy "
            f"list is not; drop it from the legacy list."
        )
    # Raises when ios.bundleConfig is set and brands/configs/<bid>.json is not
    # there. Checked HERE so it fails before anything is written, rather than
    # producing an xcconfig that promises a file the build will not find.
    bundled_config_src(bid, m)
    web_links(m)
    return ios


def warnings(m: dict, bid: str) -> list[str]:
    """Loud, but not fatal: these are legitimate pre-launch states."""
    out, ios = [], m["ios"]
    if not ios.get("storeKitProductIds"):
        out.append(f"{bid}: ios.storeKitProductIds is EMPTY -- the paywall will offer nothing. "
                   f"This is exactly the failure this system exists to prevent; confirm the "
                   f"products exist on App Store Connect record {ios.get('appStoreId')} before shipping.")
    # Both admob warnings are about a brand that COULD serve an ad and does not.
    # A brand with ios.adtech false links no ad SDK at all, so a null unit id is
    # the correct and only possible state -- warning there would train the reader
    # to ignore the warning that matters.
    if ios.get("adtech", True):
        if not ios.get("admobInterstitialId"):
            out.append(f"{bid}: ios.admobInterstitialId is null -- AdsManager FAILS CLOSED on a "
                       "missing unit, so this brand makes no ad request of any kind. The app id "
                       "alone is not enough; the unit id is what ungates serving.")
        if not ios.get("admobAppId"):
            out.append(f"{bid}: ios.admobAppId is null -- emitting Google's SAMPLE id, which is inert. "
                       f"Replace it together with ads.ios_interstitial_id, never alone.")
    legal = m.get("legal") or {}
    for k in ("contactEmail", "siteUrl"):
        if not legal.get(k):
            out.append(f"{bid}: legal.{k} is null -- the About screen hides that line. "
                       f"Fill it in before the brand ships; do not invent one.")
    return out


def paid_only(bid: str) -> bool:
    """`paid_only` from brands/configs/<bid>.json; False when absent."""
    p = CONFIGS / f"{bid}.json"
    if not p.exists():
        return False
    v = json.loads(p.read_text()).get("paid_only", False)
    if not isinstance(v, bool):
        raise BrandError(f"brands/configs/{bid}.json paid_only is {v!r}; expected true or false")
    return v


def web_links(m: dict) -> tuple[list[str], str]:
    """`deepLinkHosts` (top level, SHARED with Android's App Links) and
    `ios.applePayMerchantId`, validated. Returns (hosts, merchant id).

    Config/App.weblinks.entitlements in the iOS repo has a FIXED shape --
    applinks for the host and www.host, webcredentials for the host,
    in-app-payments for the merchant -- because an entitlements file can
    substitute a build setting into a string but cannot grow an array. So the
    manifest must match that shape exactly, and the merchant id rides on the
    same file (it is the only one that carries in-app-payments).
    """
    hosts = list(m.get("deepLinkHosts") or [])
    merchant = ((m.get("ios") or {}).get("applePayMerchantId") or "").strip()
    if hosts and (len(hosts) != 2 or hosts[1] != "www." + hosts[0]):
        raise BrandError(
            f"deepLinkHosts is {hosts!r}; iOS supports exactly [host, 'www.' + host] "
            f"(Config/App.weblinks.entitlements). Extend that file and this check together.")
    if merchant and not hosts:
        raise BrandError(
            "ios.applePayMerchantId is set but deepLinkHosts is not; the in-app-payments "
            "entitlement is signed only through Config/App.weblinks.entitlements.")
    if merchant and not merchant.startswith("merchant."):
        raise BrandError(f"ios.applePayMerchantId {merchant!r} is not a merchant id (merchant.*).")
    if hosts and not merchant:
        raise BrandError(
            "deepLinkHosts is set but ios.applePayMerchantId is not; "
            "Config/App.weblinks.entitlements always signs in-app-payments, so an empty "
            "merchant would sign an empty string. Add the id or split the file.")
    return hosts, merchant


def gen_web_links(m: dict) -> str:
    """EMITTED ONLY for a brand that declares web links, so adding this block
    leaves every other brand's generated file byte-identical. An undefined
    BRAND_* setting expands to the empty string in Info.plist, which the app
    reads as "none" (no link routing, no Apple Pay), and AppCommon.xcconfig's
    CODE_SIGN_ENTITLEMENTS falls back to the style's file."""
    hosts, merchant = web_links(m)
    if not hosts:
        return ""
    return f"""
// WEB LINKS. `deepLinkHosts` in the manifest, the same key Android's App Links
// filter is generated from. The app routes https://<host>/... (universal links)
// and the "Manage on <host>" row opens the first host. AppCommon.xcconfig signs
// BRAND_APP_ENTITLEMENTS (associated domains + Apple Pay) instead of the
// style's file; Scripts/verify-brand.sh checks the two agree, both directions.
// The website must serve /.well-known/apple-app-site-association for these.
BRAND_WEB_LINK_HOSTS = {",".join(hosts)}
BRAND_WEB_HOST = {hosts[0]}
BRAND_APP_ENTITLEMENTS = Config/App.weblinks.entitlements
// Apple Pay in the eSIM Stripe sheet (Info.plist BrandApplePayMerchantId).
BRAND_APPLE_PAY_MERCHANT_ID = {merchant}
"""


def gen_xcconfig(m: dict, src: str) -> str:
    ios, legal = m["ios"], (m.get("legal") or {})
    branding = m.get("branding") or {}
    # Absent means TRUE. A brand that has never thought about this keeps linking
    # the ad SDK, so introducing the key cannot silently delink a live brand.
    adtech = ios.get("adtech", True)
    subs = ",".join(ios.get("storeKitProductIds") or [])
    legacy = ",".join(ios.get("legacyTunnelBundleIds") or [])
    cfg_src = bundled_config_src(m["id"], m)
    cfg_on = "YES" if cfg_src else "NO"
    # The sha of the bytes this brand is SUPPOSED to bundle. verify-brand.sh
    # hashes what actually landed in the .app and compares. That is what turns
    # "selected dollarvpn, then selected rostam" from a silent wrong-policy
    # build into a build failure -- the one failure mode a presence check
    # cannot see, because the file is present either way.
    cfg_sha = (hashlib.sha256(cfg_src.read_bytes()).hexdigest() if cfg_src else "")
    # STRICT here, lenient at runtime, and the asymmetry is deliberate: the
    # generator can afford to reject a typo because a human is watching it, and
    # BrandRuntime cannot, because a hand-edited plist must still boot. Same
    # split gen-branding.py already makes for Android.
    style = branding.get("style", "classic")
    if style not in BRAND_STYLES:
        raise BrandError(
            f"branding.style is {style!r}; known styles are {sorted(BRAND_STYLES)}. "
            f"A style with no renderer would fall back to classic SILENTLY, which is "
            f"the brand-crisis bug rather than a fix for it."
        )
    # The home's NAVIGATION SHELL, separate from `style` on purpose: `style`
    # selects the composition (dial, ground, paywall field), this selects how
    # the app's top-level areas are reached. Absent means the drawer, so a
    # brand that has never thought about it keeps today's screen.
    nav = ios.get("navigation", "drawer")
    if nav not in ("drawer", "tabs"):
        raise BrandError(f"ios.navigation is {nav!r}; known values are 'drawer' and 'tabs'.")
    return f"""// {BANNER.format(src=src)}
//
// The ONE file that differs per brand. Copied to Config/Brand.xcconfig by
// Scripts/select-brand.sh, which is GITIGNORED -- so a wrong brand is a build
// failure rather than a shipped binary, and building redvpn then committing
// cannot turn the tree into redvpn for everyone.
//
// Every value below reaches Swift through the Info.plist and BrandRuntime.
// There must never be an `if BrandRuntime.id == …` in application code.

BRAND_ID = {m['id']}
BRAND_DISPLAY_NAME = {m['displayName']}
BRAND_PRODUCT_NAME = {m['displayName']}

// PERMANENT. A different bundle id is a different App Store record and cannot
// update the existing install base.
BRAND_APP_BUNDLE_ID = {ios['bundleId']}
// EXPLICIT, never derived from the app id. Renaming a live app's provider id
// orphans every saved NEVPNManager profile on every installed device.
BRAND_TUNNEL_BUNDLE_ID = {ios['tunnelBundleId']}
BRAND_APP_GROUP = {ios.get('appGroup') or 'group.' + ios['bundleId']}
BRAND_KEYCHAIN_GROUP = {ios['bundleId']}
// Per BRAND, not per machine: com.redvpn.ios is on 8Y6Q4B7AN5 whoever builds it.
BRAND_TEAM_ID = {ios['teamId']}

// Provider ids this brand shipped BEFORE. The app removes those profiles at
// launch; an orphan posts .NEVPNStatusDidChange forever and reads as a phantom
// disconnect. Legitimately empty for a brand that never shipped an extension.
BRAND_LEGACY_TUNNEL_IDS = {legacy}

BRAND_MARKETING_VERSION = {ios['marketingVersion']}
BRAND_BUILD_NUMBER = {ios['buildNumber']}

// ⚠️ A URL CANNOT be written literally in an xcconfig: `//` starts a comment and
// there is no escape, so https://host silently becomes `https:`. `$()` expands
// to the empty string and separates the slashes in the source text only.
BRAND_CASHIER_BASE = {xc(m['cashier']['base'])}
BRAND_CASHIER_KEY = {m['cashier']['brand']}
BRAND_WGTCP_API_KEY = {m.get('wgtcpApiKey', '')}
// Comma separated: a build setting cannot be an array.
BRAND_STOREKIT_IDS = {subs}
BRAND_APPSTORE_ID = {ios.get('appStoreId', '')}
// WHICH COMPOSITION THIS BRAND RENDERS -- home screen, connect dial, launch
// entry and paywall field, selected together. The SAME `branding.style` key
// Android reads into BrandStyle.kt, so the two platforms cannot draw a brand
// two different ways. Swift branches on the STYLE, never on the brand: two
// brands can select the same one, which is the property an `if id ==` cannot
// have. Unknown/absent -> classic, i.e. today's screen.
BRAND_STYLE = {style}
// HOW the top-level areas are reached: `drawer` (hamburger + menu sheet) or
// `tabs` (Home / eSIM / Account tab bar). `ios.navigation` in the manifest,
// absent = drawer. Independent of BRAND_STYLE: internetpro's `tabs` STYLE has
// its own root and ignores this.
BRAND_NAVIGATION = {nav}
// The mark's size as a fraction of the dial's core disc. MEASURED per brand off
// its own artwork, never chosen -- redvpn's 0.725 comes from the designer's own
// Shield-Indicator.png. Android has read this as `brand_mark_scale` all along;
// iOS's ConnectDial hardcoded rostam's 1040/880 aperture ratio, which is a
// property of ROSTAM'S mark and wrong for anyone else's.
BRAND_MARK_SCALE = {branding.get('markScale', 1.0)}
BRAND_HAS_MASCOT = {'YES' if branding.get('hasMascot') else 'NO'}
BRAND_DISC_FILLS_ON_CONNECT = {'NO' if branding.get('discFillsOnConnect') is False else 'YES'}
BRAND_LAUNCH_DISC_SCALE = {branding.get('launchDiscScale', 0.78)}
BRAND_LAUNCH_DISC_OFFSET_Y = {branding.get('launchDiscOffsetY', 0)}
BRAND_FEATURE_ESIM = {'YES' if (m.get('features') or {}).get('esim') else 'NO'}
BRAND_PROTECTION_NAME = {(m.get('features') or {}).get('protectionName') or ''}
// The protection API's origin, `features.protectionApiBase` (the key Android
// reads). Per brand so no binary carries another brand's host; absent =
// https://vpn.red, the default Android applies. Info.plist BrandProtectApiBase
// in the app AND the tunnel extension, which scores.
BRAND_PROTECT_API_BASE = {xc((m.get('features') or {}).get('protectionApiBase') or 'https://vpn.red')}
// PAID ONLY, as a BUILD fact. Read from brands/configs/<brand>.json
// `paid_only` (the same document Android bundles), not from the downloaded
// config: a missing or stale per-brand OTA slot falls back to the SHARED one,
// which would turn paid-only off for this brand (and a paid-only config
// landing in the shared slot would turn it on for every other brand). The app
// and the tunnel extension both read this; remote config cannot loosen it.
BRAND_PAID_ONLY = {'YES' if paid_only(m['id']) else 'NO'}
// FREE REGIONS: does this brand give the freedom regions (IR/RU/...) the free
// tier and hide purchase there? `features.freeRegions`; absent = YES, today's
// behaviour. NO = every country is treated the same: paywall, eSIM store and
// email sign-in everywhere (RedVPN, owner 2026-10-25).
BRAND_FREE_REGIONS = {'NO' if (m.get('features') or {}).get('freeRegions') is False else 'YES'}
BRAND_LEGAL_OPERATOR = {legal.get('operator') or m['displayName']}
BRAND_SUPPORT_EMAIL = {legal.get('contactEmail') or ''}
BRAND_SITE_URL = {xc(legal.get('siteUrl') or '')}
// Does this brand LINK an ad SDK at all? The exact mirror of android.adtech,
// and absent means YES, so rostam and redvpn are untouched by its introduction.
//
// 🚨 This is not "are ads switched off". Apple REJECTED RostamVPN with "An
// automated analysis of the submission indicates the app may include
// advertising but you did not select Yes for the Advertising content
// descriptor" -- the scanner reads the BINARY. DollarVPN already could not
// serve an ad (AdsManager.allowed ends in unitID != nil and its unit is null),
// yet it linked GoogleMobileAds and would have been rejected identically, while
// answering advertising=true would be a lie about a paid, ad-free product.
//
// NO additionally strips GMA's bundled PrivacyInfo.xcprivacy, which declares
// DeviceID (tracking=true) + AdvertisingData + CoarseLocation for
// ThirdPartyAdvertising and is aggregated into the app's App Privacy report --
// and which obliges ATT, in a build that deliberately carries no
// NSUserTrackingUsageDescription.
//
// It is read by Scripts/verify-brand.sh, which fails a Release build whose
// linkage disagrees with it -- so it is an interlock, not a hint.
BRAND_ADTECH = {'YES' if adtech else 'NO'}

// 🚨 EMPTY, not the sample id, when BRAND_ADTECH is NO. The sample
// `ca-app-pub-3940256099942544~1458002511` is GOOGLE'S, not ours, and it exists
// only so the SDK does not crash on an empty id -- a brand that does not link
// the SDK has nothing to crash. Scripts/verify-brand.sh deletes both keys plus
// SKAdNetworkItems from the processed Info.plist for such a brand, so neither
// value ships at all; these lines keep the xcconfig honest in the meantime.
BRAND_ADMOB_APP_ID = {(ios.get('admobAppId') or ADMOB_SAMPLE) if adtech else ''}
BRAND_ADMOB_INTERSTITIAL_ID = {(ios.get('admobInterstitialId') or '') if adtech else ''}

// RevenueCat's PUBLIC SDK key. Empty means the brand never configures the SDK
// and sells through the built-in paywall. Never the secret key: this value
// ships inside the binary by design. (iOS has no Adapty: any adaptyPublicKey /
// adaptyOnly left in a manifest is Android's and is ignored here.)
BRAND_REVENUECAT_API_KEY = {ios.get('revenuecatApiKey') or ''}

// The two footer lines under the connect dial. They were SHARED LITERALS in
// RostamVPNApp.taglineView, so every brand printed rostam's "Your Digital
// Guardian" and "Made in USA" -- the same leak gen-branding.py already fixed on
// Android, where app_tagline is emitted per flavour from this same key.
// EMPTY means the line is NOT DRAWN, never another brand's line (the rule
// legal.contactEmail already follows). Swift looks each one up as a
// LocalizedStringKey, so a value that exists in Localizable.xcstrings keeps all
// 38 locales and one that does not renders verbatim.
BRAND_TAGLINE = {branding.get('tagline') or ''}
BRAND_PROVENANCE = {branding.get('provenance') or ''}

// Does this brand ship a BOOT config? See bundled_config_src() for why this is
// opt-in and why rostam and redvpn deliberately do not take it.
// The sha is of the source bytes; Scripts/verify-brand.sh hashes what actually
// landed in the .app and fails the build on a mismatch or on a file present
// when this says NO.
BRAND_BUNDLED_CONFIG = {cfg_on}
BRAND_BUNDLED_CONFIG_SHA256 = {cfg_sha}
""" + gen_web_links(m)


def gen_theme(m: dict, src: str) -> str:
    t = (m.get("branding") or {}).get("theme") or {}

    def hexv(key, fallback):
        v = t.get(key) or fallback
        return "0x" + v.lstrip("#").upper()

    primary = hexv("primary", "#000000")
    # dark_ground() reads `accent` and falls back to `primary`, so a brand with
    # NO theme block at all (legitimate: it has no confirmed identity yet) would
    # raise a KeyError. Give it the same near-black Android's default theme
    # produces rather than failing a brand for not having colours yet.
    dt = dict(t) if t.get("primary") else {"primary": "#000000"}

    # `branding.themeDark` / `branding.themeLight`: a `tabs` brand's design
    # tokens by their design names (bg, bg2, surface, surface2, border,
    # hairline, text, muted, dim, accent, accent2, accentStrong, onAccent,
    # glow). Hex strings; an 8-digit value is the MANIFEST's convention,
    # #AARRGGBB (gen-branding.rgb, Android's Color), and is re-ordered here to
    # #RRGGBBAA, which is what the iOS side parses. Emitted as dictionaries,
    # not properties, so a key the manifest omits simply falls back to the
    # transcribed design value in the app's IPTheme, and a brand with no block
    # emits two empty dictionaries that nothing reads.
    def token_dict(block_name):
        block = (m.get("branding") or {}).get(block_name) or {}
        pairs = []
        for k in sorted(block):
            v = block[k]
            if k.startswith("_") or not isinstance(v, str):
                continue
            h = v.strip().lstrip("#")
            if len(h) not in (3, 6, 8) or any(c not in "0123456789abcdefABCDEF" for c in h):
                raise BrandError(f"branding.{block_name}.{k} is {v!r}; expected #RGB, #RRGGBB or #AARRGGBB")
            if len(h) == 8:  # AARRGGBB -> RRGGBBAA
                h = h[2:] + h[:2]
            pairs.append(f'"{k}": "#{h.upper()}"')
        return "[" + ", ".join(pairs) + "]" if pairs else "[:]"
    theme_dark = token_dict("themeDark")
    theme_light = token_dict("themeLight")
    return f"""// {BANNER.format(src=src)}
//
// The iOS mirror of Android's generated BrandPalette.kt: the SAME
// `branding.theme` block in the SAME manifest, so the two platforms cannot show
// a user different brand colours.
//
// Copied into rostamvpn/Brand/ by Scripts/select-brand.sh, which is GITIGNORED.
// Colours ONLY. Identity travels xcconfig -> Info.plist -> BrandRuntime.

import SwiftUI

enum BrandTheme {{
    private static func hex(_ v: UInt32) -> Color {{
        Color(
            red:   Double((v >> 16) & 0xFF) / 255,
            green: Double((v >> 8) & 0xFF) / 255,
            blue:  Double(v & 0xFF) / 255
        )
    }}

    static let primary       = hex({primary})
    static let primaryDeep   = hex({hexv('primaryDeep', t.get('primary', '#000000'))})
    static let secondary     = hex({hexv('secondary', t.get('primary', '#000000'))})
    static let accent        = hex({hexv('accent', t.get('secondary', '#000000'))})
    static let accentOnLight = hex({hexv('accentOnLight', t.get('accent', '#000000'))})
    static let success       = hex({hexv('success', '#45988A')})
    static let danger        = hex({hexv('danger', '#D32F2F')})
    static let warning       = hex({hexv('warning', '#D7A23E')})
    static let background    = hex({hexv('background', '#F5F5F5')})
    static let ink           = hex({hexv('ink', '#2D3436')})

    /// The connect ring, when a brand wants it off-primary. DollarVPN's mark is
    /// a gold coin and the ring defaulted to its dark green, a colour the coin
    /// has nothing to do with. Brands that omit `theme.ring` keep `primary`,
    /// which is right for Rostam: the teal ring and the gold horns are
    /// deliberately different colours.
    static let ring          = hex({hexv('ring', t.get('primary', '#000000'))})
    /// Opacity of the ring's socket track when DISCONNECTED. 0.15 is tuned for
    /// teal on an off-white ground; gold on cream disappears entirely at that.
    static let ringRestAlpha = {t.get('ringRestAlpha', 0.15)}

    // ── THE DARK TREATMENT'S GROUND ──
    //
    // Emitted for EVERY brand so the value has ONE source, exactly as Android's
    // BrandPalette does; a brand on a light treatment simply never reads them.
    // Both come from gen-branding.py's own `dark_ground`/`dark_card`, IMPORTED
    // rather than reimplemented, so Android's BrandPalette.kt and this file
    // cannot drift.
    //
    /// 10% of the brand's own accent mixed into a near-black. RedVPN's #69108C
    /// lands on #191020, a violet-black -- the hue is what stops a dark app
    /// reading as "the OS dark theme" instead of as itself.
    static let groundDark    = hex({"0x" + dark_ground(dt).lstrip("#").upper()})
    /// One step lighter: the card fill on that ground. 7% white.
    static let cardDark      = hex({"0x" + dark_card(dt).lstrip("#").upper()})

    /// 6% of the brand's own accent mixed into WHITE -- the inverse of
    /// `groundDark`, from the same `gen-branding.py` so the platforms cannot
    /// drift. RedVPN lands on #F6F1F8.
    ///
    /// 🚨 A `rings` brand's dial is a WHITE disc carrying a mark drawn for
    /// white. On a white page that disc measures 1.12:1 against its own
    /// background and the hero of the dark screen dissolves. Tinting the PAGE
    /// is what turns white back into figure; restyling the disc would need a
    /// dark-knockout variant of an asset that has none, i.e. new artwork.
    static let groundLight   = hex({"0x" + light_ground(dt).lstrip("#").upper()})

    // ── THE TABS TREATMENT'S TOKENS ──
    //
    /// `branding.themeDark`, by design token name. Empty for brands without
    /// one; IPTheme uses its transcribed value for any missing key.
    static let themeDark: [String: String] = {theme_dark}
    /// `branding.themeLight`, same contract.
    static let themeLight: [String: String] = {theme_light}
}}
"""


def gen_icon(bid: str, dest: pathlib.Path) -> str | None:
    """Build the AppIcon from a 1024 master, or say plainly why it did not."""
    appicon = dest / "AppIcon.appiconset"
    # `ios-icon.png` first: an iOS-only master, deliberately NOT named icon.png.
    # gen-branding.py regenerates every ANDROID density from icon.png, and a
    # brand can legitimately ship hand-tuned per-density Android art that a
    # single downscaled master cannot reproduce -- redvpn does. Naming the iOS
    # master separately lets iOS have one without destroying that art.
    src = ASSETS / bid / "ios-icon.png"
    if not src.exists():
        src = ASSETS / bid / "icon.png"
    if not src.exists():
        if appicon.exists():
            return (f"{bid}: no brands/assets/{bid}/ios-icon.png or icon.png, so the EXISTING "
                    f"AppIcon.appiconset was left alone. It is not regenerated and may be "
                    f"stale -- an icon frozen before a rename is exactly the trap this "
                    f"used to hit silently.")
        return (f"{bid}: NO APP ICON. neither brands/assets/{bid}/ios-icon.png nor icon.png exists, so none "
                f"was generated and none is present. The build will ship without an icon. "
                f"Add a 1024x1024 master; a smaller one is NOT upscaled here, because a "
                f"blurry App Store icon is worse than an obvious missing one.")
    w = subprocess.run(["sips", "-g", "pixelWidth", str(src)], capture_output=True, text=True)
    px = int(w.stdout.strip().split(":")[-1]) if ":" in w.stdout else 0
    if px < IOS_ICON:
        return (f"{bid}: {src.name} is {px}px, below the {IOS_ICON}px "
                f"App Store icon. NOT upscaled and NOT written -- supply a real master.")
    appicon.mkdir(parents=True, exist_ok=True)
    subprocess.run(["sips", "-Z", str(IOS_ICON), str(src), "--out", str(appicon / "icon-1024.png")],
                   capture_output=True, check=False)
    (appicon / "Contents.json").write_text(json.dumps({
        "images": [{"filename": "icon-1024.png", "idiom": "universal",
                    "platform": "ios", "size": "1024x1024"}],
        "info": {"author": "gen-ios.py", "version": 1},
    }, indent=2) + "\n")
    return None


def gen_dial_mark(bid: str, dest: pathlib.Path) -> str | None:
    """Emit BrandDialMark, the face of the connect dial, as an ASSET.

    It used to be ~200 lines of Rostam path data compiled into every brand's
    binary behind a `hasMascot` gate -- which makes the gate meaningless the
    moment a second brand sets it, and DollarVPN does, with a coin.

    THE CANVAS CONVENTION, which is load-bearing: the art sits on a SQUARE
    canvas whose APERTURE -- the circle ConnectDial sizes to the dial's disc --
    is 880/1040 = 84.6% of the width. ConnectDial multiplies discSize by
    1040/880, so anything drawn OUTSIDE that circle (Rostam's horns) deliberately
    overflows and crosses in front of the state ring. Art that fills the whole
    canvas will overflow the ring by 18%.

    SVG is preferred and kept as a vector; PNG is copied as-is.
    """
    out = dest / "BrandDialMark.imageset"
    svg = ASSETS / bid / "dial-mark.svg"
    png = ASSETS / bid / "dial-mark.png"
    if svg.exists():
        out.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(svg, out / "BrandDialMark.svg")
        (out / "Contents.json").write_text(json.dumps({
            "images": [{"filename": "BrandDialMark.svg", "idiom": "universal"}],
            "info": {"author": "gen-ios.py", "version": 1},
            # Keeps it a VECTOR in Assets.car, so the dial stays crisp at any size.
            "properties": {"preserves-vector-representation": True},
        }, indent=2) + "\n")
        return None
    if png.exists():
        out.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(png, out / "BrandDialMark.png")
        (out / "Contents.json").write_text(json.dumps({
            "images": [{"idiom": "universal", "scale": "1x"},
                       {"idiom": "universal", "scale": "2x"},
                       {"filename": "BrandDialMark.png", "idiom": "universal", "scale": "3x"}],
            "info": {"author": "gen-ios.py", "version": 1},
        }, indent=2) + "\n")
        return None
    if out.exists():
        # NEVER delete a hand-placed imageset. Same rule as gen_icon and gen_art:
        # a brand's art can legitimately be a file somebody put there rather than
        # something this tool can rebuild, and silently removing it would blank
        # the connect dial with no error anywhere.
        return (f"{bid}: Brand.xcassets/BrandDialMark.imageset exists but there is no "
                f"brands/assets/{bid}/dial-mark.svg or .png to regenerate it from. "
                f"Left untouched; it is not reproducible from the manifests.")
    return None


def _imageset(out: pathlib.Path, src: pathlib.Path, name: str, scale: str = "3x") -> None:
    out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, out / f"{name}{src.suffix}")
    images = [{"idiom": "universal", "scale": s} for s in ("1x", "2x", "3x")]
    for i in images:
        if i["scale"] == scale:
            i["filename"] = f"{name}{src.suffix}"
    (out / "Contents.json").write_text(json.dumps(
        {"images": images, "info": {"author": "gen-ios.py", "version": 1}}, indent=2) + "\n")


def gen_art(bid: str, m: dict, cat: pathlib.Path) -> list[str]:
    """Fill in the per-brand image sets the app draws by name.

    NEVER OVERWRITES an existing imageset. rostam's launch art and mascot are
    hand-made files moved out of the shared catalog, not generated, and
    regenerating them from a logo would silently change a live app's launch
    screen. A brand that has one keeps it; a brand that does not gets one built
    from its manifest, and anything still missing is reported.

    This matters because a missing image is SILENT on iOS: SwiftUI draws
    nothing, the build succeeds, and the launch screen is simply blank.
    """
    warns: list[str] = []
    a = ASSETS / bid
    theme = (m.get("branding") or {}).get("theme") or {}

    for name, src_names in (("LaunchLogo", ("launch-logo.png", "logo.png")),
                            ("BrandMascot", ("mascot.png", "logo.png"))):
        out = cat / f"{name}.imageset"
        if out.exists():
            continue
        src = next((a / n for n in src_names if (a / n).exists()), None)
        if src is None:
            warns.append(f"{bid}: no source for {name} (looked for {', '.join(src_names)} in "
                         f"brands/assets/{bid}/). The app draws Image(\"{name}\") and a missing "
                         f"image renders as NOTHING, with no error.")
            continue
        _imageset(out, src, name)

    out = cat / "LaunchGradient.imageset"
    if not out.exists():
        try:
            from PIL import Image
        except ImportError:
            warns.append(f"{bid}: Pillow unavailable, so no LaunchGradient was generated. "
                         f"The launch screen will have no background. pip install Pillow.")
            return warns
        # A brand may specify its entry explicitly. Without this the gradient is
        # always primaryDeep -> background, which for a red brand is a full red
        # wash: the owner's words were that the splash "has red background fucked
        # up". Android already ships this brand a dark violet-black entry; these
        # keys are how iOS gets the same one instead of deriving a different
        # answer from the same manifest.
        top = (theme.get("launchTop") or theme.get("launchDeep")
               or theme.get("primaryDeep") or theme.get("primary") or "#000000")
        bot = (theme.get("launchBottom") or theme.get("background") or "#FFFFFF")

        def rgb(h):
            h = h.lstrip("#")
            return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

        t0, t1 = rgb(top), rgb(bot)
        w, h = 393, 852
        img = Image.new("RGB", (w, h))
        px = img.load()
        for y in range(h):
            f = y / (h - 1)
            c = tuple(round(t0[i] + (t1[i] - t0[i]) * f) for i in range(3))
            for x in range(w):
                px[x, y] = c
        tmp = cat / "_launch_gradient_tmp.png"
        img.save(tmp)
        _imageset(out, tmp, "LaunchGradient", scale="1x")
        tmp.unlink()
    return warns


def main() -> int:
    argv = sys.argv[1:]
    check_only = "--check" in argv
    if "--ios-repo" not in argv:
        print("error: --ios-repo <path to rostamvpn-ios> is required.\n"
              "       This tool writes into the iOS repo on purpose. Emitting into this\n"
              "       repo and trusting somebody to copy it is what shipped an empty\n"
              "       paywall once already.", file=sys.stderr)
        return 2
    ios_repo = pathlib.Path(argv[argv.index("--ios-repo") + 1]).expanduser().resolve()
    if not (ios_repo / "rostamvpn.xcodeproj").is_dir():
        print(f"error: {ios_repo} does not look like the iOS repo", file=sys.stderr)
        return 2

    skip = {"--check", "--ios-repo", str(ios_repo), argv[argv.index("--ios-repo") + 1]}
    args = [a for a in argv if a not in skip and not a.startswith("--")]

    manifests = {f.stem: json.loads(f.read_text())
                 for f in sorted(BRANDS.glob("*.json")) if f.name != "LOCKED.json"}
    wanted = args or sorted(manifests)

    written, skipped, warns, errors, drift = [], [], [], [], []
    for bid in wanted:
        m = manifests.get(bid)
        if m is None:
            print(f"  ERROR unknown brand {bid!r}", file=sys.stderr)
            return 2
        if not (m.get("ios") or {}).get("bundleId"):
            # Not an error: a brand can exist on Android before it exists on iOS.
            # Emitting a guessed bundle id would be far worse than emitting none.
            skipped.append(f"{bid}: no ios.bundleId -- not an iOS product yet")
            continue
        try:
            check(m, bid)
        except BrandError as e:
            errors.append(f"{bid}: {e}")
            continue

        d = ios_repo / "Brands" / bid
        files = {
            d / "Brand.xcconfig": gen_xcconfig(m, f"{bid}.json"),
            d / "BrandTheme.swift": gen_theme(m, f"{bid}.json"),
        }
        # COPIED, never rendered: the bytes must match what Android overlays.
        cfg_src = bundled_config_src(bid, m)
        cfg_dst = d / "default-config.json"
        if check_only:
            for path, body in files.items():
                if not path.exists() or path.read_text() != body:
                    drift.append(str(path.relative_to(ios_repo)))
            # A config left behind after the flag was turned OFF is drift too:
            # select-brand.sh would still copy it into the build.
            if cfg_src is None:
                if cfg_dst.exists():
                    drift.append(f"{cfg_dst.relative_to(ios_repo)} (stale: ios.bundleConfig is not set)")
            elif not cfg_dst.exists() or cfg_dst.read_bytes() != cfg_src.read_bytes():
                drift.append(str(cfg_dst.relative_to(ios_repo)))
            continue

        d.mkdir(parents=True, exist_ok=True)
        cat = d / "Brand.xcassets"
        cat.mkdir(exist_ok=True)
        (cat / "Contents.json").write_text(
            json.dumps({"info": {"author": "gen-ios.py", "version": 1}}, indent=2) + "\n")
        for path, body in files.items():
            path.write_text(body)
        # UNCONDITIONAL remove, then copy. Turning the flag off must delete the
        # file, or select-brand.sh keeps shipping a config the manifest no
        # longer claims -- the same reason Brand.xcassets is rm -rf'd below.
        cfg_dst.unlink(missing_ok=True)
        if cfg_src is not None:
            shutil.copyfile(cfg_src, cfg_dst)
        w = gen_icon(bid, cat)
        if w:
            warns.append(w)
        # The connect dial draws Image("BrandDialMark") when hasMascot is true.
        # A MISSING asset renders as nothing at all -- a blank dial, no error --
        # so say so here rather than let it ship. rostam's is a vector SVG
        # transcribed from Android's brand_mark.xml.
        gen_dial_mark(bid, cat)
        warns.extend(gen_art(bid, m, cat))
        if (m.get("branding") or {}).get("hasMascot") and not (cat / "BrandDialMark.imageset").exists():
            warns.append(f"{bid}: branding.hasMascot is TRUE but "
                         f"Brands/{bid}/Brand.xcassets/BrandDialMark.imageset does not exist. "
                         f"The connect dial will draw NOTHING -- a blank ring, with no error. "
                         f"Add brands/assets/{bid}/dial-mark.svg (preferred) or dial-mark.png, "
                         f"on a square canvas whose aperture circle is 880/1040 of the width, "
                         f"or set branding.hasMascot false.")
        warns.extend(warnings(m, bid))
        written.append(bid)

    if check_only:
        if drift:
            print("error: generated files are stale, re-run gen-ios.py:", file=sys.stderr)
            for f in drift:
                print(f"  {f}", file=sys.stderr)
            return 1
        print("  generated iOS brand files are up to date")
        return 0

    for b in written:
        extra = (", default-config.json"
                 if (ios_repo / "Brands" / b / "default-config.json").exists() else "")
        print(f"  wrote {ios_repo.name}/Brands/{b}/  "
              f"(Brand.xcconfig, BrandTheme.swift, Brand.xcassets{extra})")
    for s in skipped:
        print(f"  skip  {s}")
    for w in warns:
        print(f"  WARNING {w}")
    for e in errors:
        print(f"  ERROR   {e}", file=sys.stderr)
    if written:
        print(f"\n  next: cd {ios_repo} && Scripts/select-brand.sh <brand>")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
