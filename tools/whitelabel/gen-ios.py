import importlib.util
import json
import pathlib
import shutil
import subprocess
import sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
BRANDS = ROOT / "brands"
ASSETS = BRANDS / "assets"
CONFIGS = BRANDS / "configs"
LOCKED = json.loads((BRANDS / "LOCKED.json").read_text())
BANNER = "GENERATED by tools/whitelabel/gen-ios.py from brands/{src} -- DO NOT EDIT."
_gb_spec = importlib.util.spec_from_file_location(
    "_gen_branding", pathlib.Path(__file__).with_name("gen-branding.py"))
_gb = importlib.util.module_from_spec(_gb_spec)
_gb_spec.loader.exec_module(_gb)
BRAND_STYLES = {"classic", "rings", "value", "tabs"}
dark_ground = _gb.dark_ground
light_ground = _gb.light_ground
dark_card = _gb.dark_card
DARK_STYLES = {"rings"}
IOS_ICON = 1024


class BrandError(Exception):
    pass


def bundled_config_src(bid: str, m: dict) -> pathlib.Path | None:
    """The config this brand bundles as its BOOT config, or None.

    OPT-IN via `ios.bundleConfig`, and the opt-in is the whole design. iOS has
    never bundled a config at ALL -- `RedSocketTunnel/default-config.json` has
    zero pbxproj references, both Resources phases are empty, and no built .app
    contains any JSON -- so before its first successful fetch every brand runs
    `ConfigPolicy.Snapshot.fallback`: ads OFF, throttle OFF, freedom tier ON.

    That means handing a LIVE brand a boot config is a behaviour change, not a
    no-op: rostam's own config carries throttle 2000, which would become true at
    first launch where today it is false. rostam therefore does not opt in and
    keeps `Snapshot.fallback` exactly.

    A brand opts in only when its policy is the OPPOSITE of the fallback in the
    places the first screen talks about (`freedom_tier` false, `hard_stop` true).
    """
    if not (m.get("ios") or {}).get("bundleConfig"):
        return None
    src = CONFIGS / f"{bid}.json"
    if not src.is_file():
        raise BrandError(
            f"ios.bundleConfig is true but {src.relative_to(ROOT)} does not exist. "
            f"The bundled config is COPIED from that file, never written here, so that "
            f"iOS and Android cannot hold different policy for one brand -- Android "
            f"overlays the same bytes as src/{bid}/assets/default-config.json."
        )
    return src


def assert_icon_opaque(path):
    """App Store icons may not have an alpha channel. Fail here, not at upload.

    ITMS-90717 rejects a transparent icon at the very last step, after a full
    archive and upload, and iOS composites the transparent regions on black on
    the home screen. `sips -Z` preserves alpha, so copying a source icon is not
    enough. A genuinely transparent RGBA icon shipped this way once and nothing
    caught it: the size guard checks size, and the brand verifier only checks
    that an AppIcon exists.
    """
    try:
        from PIL import Image
    except ImportError:
        return
    im = Image.open(path)
    if im.mode in ("RGBA", "LA") and im.getextrema()[-1][0] < 255:
        raise SystemExit(
            f"{path}: App Store icon has real transparency and would be "
            f"rejected as ITMS-90717. Composite it on the brand background first."
        )


def xc(value: str) -> str:
    """Escape a value for an xcconfig.

    An xcconfig strips everything after `//` as a COMMENT and has no escape,
    so `https://cashier.example.com` written literally becomes `https:`. That shipped
    once and was caught only by diffing the built Info.plist against a baseline.
    `$()` expands to the empty string, which separates the two slashes in the
    source text without changing the value. Scripts/verify-brand.sh in the iOS
    repo also asserts the URL keys still look like URLs after substitution.
    """
    return value.replace("//", "/$()/")


def check(m: dict, bid: str) -> dict:
    """Hard-fail on anything that would ship a silently wrong iOS build."""
    ios = m.get("ios") or {}
    locked = (LOCKED.get(bid) or {}).get("ios") or {}
    def need(key):
        v = ios.get(key)
        if v in (None, "", []):
            raise BrandError(f"ios.{key} is missing; it cannot be guessed")
        return v
    bundle = need("bundleId")
    tunnel = need("tunnelBundleId")
    need("teamId")
    need("marketingVersion")
    if ios.get("buildNumber") in (None, ""):
        raise BrandError(
            "ios.buildNumber is missing. Read it from App Store Connect "
            "(GET /v1/builds?filter[app]=<appStoreId>&sort=-uploadedDate) and record "
            "how you read it. An expired build still burns its number, and a number "
            "already used is rejected at the last step of an upload."
        )
    for key, want in (("bundleId", locked.get("bundleId")),
                      ("tunnelBundleId", locked.get("tunnelBundleId")),
                      ("teamId", locked.get("teamId"))):
        if want and ios.get(key) != want:
            raise BrandError(f"ios.{key} is {ios.get(key)!r} but LOCKED.json says {want!r}. "
                             f"These identifiers are PERMANENT; fix the manifest, not LOCKED.json.")
    if not tunnel.startswith(bundle + "."):
        raise BrandError(f"ios.tunnelBundleId {tunnel!r} is not prefixed by ios.bundleId {bundle!r}. "
                         f"iOS refuses to load an app extension that is not under its container app.")
    if tunnel.endswith(".tunnel") and bid == "rostam":
        raise BrandError("rostam's tunnel id must stay .redsocket; renaming a live app's "
                         "provider id orphans every saved NEVPNManager profile on every device.")
    if tunnel in (ios.get("legacyTunnelBundleIds") or []):
        raise BrandError(
            f"ios.tunnelBundleId {tunnel!r} is ALSO in ios.legacyTunnelBundleIds. "
            f"TunnelProfile.removeStaleProfiles() deletes every profile in that list at "
            f"launch, so the app would delete its own VPN profile on every launch and tear "
            f"down a live tunnel. This happens when tunnelBundleId is changed and the legacy "
            f"list is not; drop it from the legacy list."
        )
    bundled_config_src(bid, m)
    return ios


def warnings(m: dict, bid: str) -> list[str]:
    """Loud, but not fatal: these are legitimate pre-launch states."""
    out, ios = [], m["ios"]
    if not ios.get("storeKitProductIds"):
        out.append(f"{bid}: ios.storeKitProductIds is EMPTY -- the paywall will offer nothing. "
                   f"This is exactly the failure this system exists to prevent; confirm the "
                   f"products exist on App Store Connect record {ios.get('appStoreId')} before shipping.")
    legal = m.get("legal") or {}
    for k in ("contactEmail", "siteUrl"):
        if not legal.get(k):
            out.append(f"{bid}: legal.{k} is null -- the About screen hides that line. "
                       f"Fill it in before the brand ships; do not invent one.")
    return out


def paid_only(bid: str) -> bool:
    """`paid_only` from brands/configs/<bid>.json; False when absent."""
    p = CONFIGS / f"{bid}.json"
    if not p.exists():
        return False
    v = json.loads(p.read_text()).get("paid_only", False)
    if not isinstance(v, bool):
        raise BrandError(f"brands/configs/{bid}.json paid_only is {v!r}; expected true or false")
    return v


def gen_xcconfig(m: dict, src: str) -> str:
    ios, legal = m["ios"], (m.get("legal") or {})
    branding = m.get("branding") or {}
    subs = ",".join(ios.get("storeKitProductIds") or [])
    legacy = ",".join(ios.get("legacyTunnelBundleIds") or [])
    cfg_src = bundled_config_src(m["id"], m)
    cfg_on = "YES" if cfg_src else "NO"
    cfg_sha = (hashlib.sha256(cfg_src.read_bytes()).hexdigest() if cfg_src else "")
    style = branding.get("style", "classic")
    if style not in BRAND_STYLES:
        raise BrandError(
            f"branding.style is {style!r}; known styles are {sorted(BRAND_STYLES)}. "
            f"A style with no renderer would fall back to classic SILENTLY, which is "
            f"the brand-crisis bug rather than a fix for it."
        )
    return f"""// {BANNER.format(src=src)}
BRAND_ID = {m['id']}
BRAND_DISPLAY_NAME = {m['displayName']}
BRAND_PRODUCT_NAME = {m['displayName']}
BRAND_APP_BUNDLE_ID = {ios['bundleId']}
BRAND_TUNNEL_BUNDLE_ID = {ios['tunnelBundleId']}
BRAND_APP_GROUP = {ios.get('appGroup') or 'group.' + ios['bundleId']}
BRAND_KEYCHAIN_GROUP = {ios['bundleId']}
BRAND_TEAM_ID = {ios['teamId']}
BRAND_LEGACY_TUNNEL_IDS = {legacy}
BRAND_MARKETING_VERSION = {ios['marketingVersion']}
BRAND_BUILD_NUMBER = {ios['buildNumber']}
BRAND_CASHIER_BASE = {xc(m['cashier']['base'])}
BRAND_CASHIER_KEY = {m['cashier']['brand']}
BRAND_WGTCP_API_KEY = {m.get('wgtcpApiKey', '')}
BRAND_STOREKIT_IDS = {subs}
BRAND_APPSTORE_ID = {ios.get('appStoreId', '')}
BRAND_STYLE = {style}
BRAND_MARK_SCALE = {branding.get('markScale', 1.0)}
BRAND_HAS_MASCOT = {'YES' if branding.get('hasMascot') else 'NO'}
BRAND_DISC_FILLS_ON_CONNECT = {'NO' if branding.get('discFillsOnConnect') is False else 'YES'}
BRAND_LAUNCH_DISC_SCALE = {branding.get('launchDiscScale', 0.78)}
BRAND_LAUNCH_DISC_OFFSET_Y = {branding.get('launchDiscOffsetY', 0)}
BRAND_PAID_ONLY = {'YES' if paid_only(m['id']) else 'NO'}
BRAND_LEGAL_OPERATOR = {legal.get('operator') or m['displayName']}
BRAND_SUPPORT_EMAIL = {legal.get('contactEmail') or ''}
BRAND_SITE_URL = {xc(legal.get('siteUrl') or '')}
BRAND_TAGLINE = {branding.get('tagline') or ''}
BRAND_PROVENANCE = {branding.get('provenance') or ''}
BRAND_BUNDLED_CONFIG = {cfg_on}
BRAND_BUNDLED_CONFIG_SHA256 = {cfg_sha}
"""


def gen_theme(m: dict, src: str) -> str:
    t = (m.get("branding") or {}).get("theme") or {}
    def hexv(key, fallback):
        v = t.get(key) or fallback
        return "0x" + v.lstrip("#").upper()
    primary = hexv("primary", "#000000")
    dt = dict(t) if t.get("primary") else {"primary": "#000000"}
    def token_dict(block_name):
        block = (m.get("branding") or {}).get(block_name) or {}
        pairs = []
        for k in sorted(block):
            v = block[k]
            if k.startswith("_") or not isinstance(v, str):
                continue
            h = v.strip().lstrip("#")
            if len(h) not in (3, 6, 8) or any(c not in "0123456789abcdefABCDEF" for c in h):
                raise BrandError(f"branding.{block_name}.{k} is {v!r}; expected #RGB, #RRGGBB or #AARRGGBB")
            if len(h) == 8:
                h = h[2:] + h[:2]
            pairs.append(f'"{k}": "#{h.upper()}"')
        return "[" + ", ".join(pairs) + "]" if pairs else "[:]"
    theme_dark = token_dict("themeDark")
    theme_light = token_dict("themeLight")
    return f"""// Copyright 2026 Internet Mastering & Company, Inc.
// SPDX-License-Identifier: Apache-2.0

import SwiftUI

enum BrandTheme {{
    private static func hex(_ v: UInt32) -> Color {{
        Color(
            red:   Double((v >> 16) & 0xFF) / 255,
            green: Double((v >> 8) & 0xFF) / 255,
            blue:  Double(v & 0xFF) / 255
        )
    }}

    static let primary       = hex({primary})
    static let primaryDeep   = hex({hexv('primaryDeep', t.get('primary', '#000000'))})
    static let secondary     = hex({hexv('secondary', t.get('primary', '#000000'))})
    static let accent        = hex({hexv('accent', t.get('secondary', '#000000'))})
    static let accentOnLight = hex({hexv('accentOnLight', t.get('accent', '#000000'))})
    static let success       = hex({hexv('success', '#45988A')})
    static let danger        = hex({hexv('danger', '#D32F2F')})
    static let warning       = hex({hexv('warning', '#D7A23E')})
    static let background    = hex({hexv('background', '#F5F5F5')})
    static let ink           = hex({hexv('ink', '#2D3436')})

    /// The connect ring, when a brand wants it off-primary: a mark whose colour has
    /// nothing to do with `primary` should not sit inside a ring of it.
    static let ring          = hex({hexv('ring', t.get('primary', '#000000'))})

    /// Opacity of the ring's socket track when DISCONNECTED. 0.15 is tuned for teal
    /// on an off-white ground; gold on cream disappears entirely at that.
    static let ringRestAlpha = {t.get('ringRestAlpha', 0.15)}

    /// 10% of the brand's own accent mixed into a near-black -- the hue is what
    /// stops a dark app reading as "the OS dark theme" instead of as itself.
    static let groundDark    = hex({"0x" + dark_ground(dt).lstrip("#").upper()})
    /// One step lighter: the card fill on that ground. 7% white.
    static let cardDark      = hex({"0x" + dark_card(dt).lstrip("#").upper()})
    /// 6% of the brand's own accent mixed into WHITE -- the inverse of
    /// `groundDark`, from the same `gen-branding.py` so the platforms cannot drift.
    static let groundLight   = hex({"0x" + light_ground(dt).lstrip("#").upper()})

    /// `branding.themeDark`, by design token name. Empty for brands without one;
    /// IPTheme uses its transcribed value for any missing key.
    static let themeDark: [String: String] = {theme_dark}
    /// `branding.themeLight`, same contract.
    static let themeLight: [String: String] = {theme_light}
}}
"""


def gen_icon(bid: str, dest: pathlib.Path) -> str | None:
    """Build the AppIcon from a 1024 master, or say plainly why it did not."""
    appicon = dest / "AppIcon.appiconset"
    src = ASSETS / bid / "ios-icon.png"
    if not src.exists():
        src = ASSETS / bid / "icon.png"
    if not src.exists():
        if appicon.exists():
            return (f"{bid}: no brands/assets/{bid}/ios-icon.png or icon.png, so the EXISTING "
                    f"AppIcon.appiconset was left alone. It is not regenerated and may be "
                    f"stale -- an icon frozen before a rename is exactly the trap this "
                    f"used to hit silently.")
        return (f"{bid}: NO APP ICON. neither brands/assets/{bid}/ios-icon.png nor icon.png exists, so none "
                f"was generated and none is present. The build will ship without an icon. "
                f"Add a 1024x1024 master; a smaller one is NOT upscaled here, because a "
                f"blurry App Store icon is worse than an obvious missing one.")
    w = subprocess.run(["sips", "-g", "pixelWidth", str(src)], capture_output=True, text=True)
    px = int(w.stdout.strip().split(":")[-1]) if ":" in w.stdout else 0
    if px < IOS_ICON:
        return (f"{bid}: {src.name} is {px}px, below the {IOS_ICON}px "
                f"App Store icon. NOT upscaled and NOT written -- supply a real master.")
    appicon.mkdir(parents=True, exist_ok=True)
    subprocess.run(["sips", "-Z", str(IOS_ICON), str(src), "--out", str(appicon / "icon-1024.png")],
                   capture_output=True, check=False)
    (appicon / "Contents.json").write_text(json.dumps({
        "images": [{"filename": "icon-1024.png", "idiom": "universal",
                    "platform": "ios", "size": "1024x1024"}],
        "info": {"author": "gen-ios.py", "version": 1},
    }, indent=2) + "\n")
    return None


def gen_dial_mark(bid: str, dest: pathlib.Path) -> str | None:
    """Emit BrandDialMark, the face of the connect dial, as an ASSET.

    It used to be ~200 lines of Rostam path data compiled into every brand's
    binary behind a `hasMascot` gate -- which makes the gate meaningless the
    moment a second brand sets it.

    THE CANVAS CONVENTION, which is load-bearing: the art sits on a SQUARE
    canvas whose APERTURE -- the circle ConnectDial sizes to the dial's disc --
    is 880/1040 = 84.6% of the width. ConnectDial multiplies discSize by
    1040/880, so anything drawn OUTSIDE that circle (Rostam's horns) deliberately
    overflows and crosses in front of the state ring. Art that fills the whole
    canvas will overflow the ring by 18%.

    SVG is preferred and kept as a vector; PNG is copied as-is.
    """
    out = dest / "BrandDialMark.imageset"
    svg = ASSETS / bid / "dial-mark.svg"
    png = ASSETS / bid / "dial-mark.png"
    if svg.exists():
        out.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(svg, out / "BrandDialMark.svg")
        (out / "Contents.json").write_text(json.dumps({
            "images": [{"filename": "BrandDialMark.svg", "idiom": "universal"}],
            "info": {"author": "gen-ios.py", "version": 1},
            "properties": {"preserves-vector-representation": True},
        }, indent=2) + "\n")
        return None
    if png.exists():
        out.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(png, out / "BrandDialMark.png")
        (out / "Contents.json").write_text(json.dumps({
            "images": [{"idiom": "universal", "scale": "1x"},
                       {"idiom": "universal", "scale": "2x"},
                       {"filename": "BrandDialMark.png", "idiom": "universal", "scale": "3x"}],
            "info": {"author": "gen-ios.py", "version": 1},
        }, indent=2) + "\n")
        return None
    if out.exists():
        return (f"{bid}: Brand.xcassets/BrandDialMark.imageset exists but there is no "
                f"brands/assets/{bid}/dial-mark.svg or .png to regenerate it from. "
                f"Left untouched; it is not reproducible from the manifests.")
    return None


def _imageset(out: pathlib.Path, src: pathlib.Path, name: str, scale: str = "3x") -> None:
    out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, out / f"{name}{src.suffix}")
    images = [{"idiom": "universal", "scale": s} for s in ("1x", "2x", "3x")]
    for i in images:
        if i["scale"] == scale:
            i["filename"] = f"{name}{src.suffix}"
    (out / "Contents.json").write_text(json.dumps(
        {"images": images, "info": {"author": "gen-ios.py", "version": 1}}, indent=2) + "\n")


def gen_art(bid: str, m: dict, cat: pathlib.Path) -> list[str]:
    """Fill in the per-brand image sets the app draws by name.

    NEVER OVERWRITES an existing imageset. rostam's launch art and mascot are
    hand-made files moved out of the shared catalog, not generated, and
    regenerating them from a logo would silently change a live app's launch
    screen. A brand that has one keeps it; a brand that does not gets one built
    from its manifest, and anything still missing is reported.

    This matters because a missing image is SILENT on iOS: SwiftUI draws
    nothing, the build succeeds, and the launch screen is simply blank.
    """
    warns: list[str] = []
    a = ASSETS / bid
    theme = (m.get("branding") or {}).get("theme") or {}
    for name, src_names in (("LaunchLogo", ("launch-logo.png", "logo.png")),
                            ("BrandMascot", ("mascot.png", "logo.png"))):
        out = cat / f"{name}.imageset"
        if out.exists():
            continue
        src = next((a / n for n in src_names if (a / n).exists()), None)
        if src is None:
            warns.append(f"{bid}: no source for {name} (looked for {', '.join(src_names)} in "
                         f"brands/assets/{bid}/). The app draws Image(\"{name}\") and a missing "
                         f"image renders as NOTHING, with no error.")
            continue
        _imageset(out, src, name)
    out = cat / "LaunchGradient.imageset"
    if not out.exists():
        try:
            from PIL import Image
        except ImportError:
            warns.append(f"{bid}: Pillow unavailable, so no LaunchGradient was generated. "
                         f"The launch screen will have no background. pip install Pillow.")
            return warns
        top = (theme.get("launchTop") or theme.get("launchDeep")
               or theme.get("primaryDeep") or theme.get("primary") or "#000000")
        bot = (theme.get("launchBottom") or theme.get("background") or "#FFFFFF")
        def rgb(h):
            h = h.lstrip("#")
            return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
        t0, t1 = rgb(top), rgb(bot)
        w, h = 393, 852
        img = Image.new("RGB", (w, h))
        px = img.load()
        for y in range(h):
            f = y / (h - 1)
            c = tuple(round(t0[i] + (t1[i] - t0[i]) * f) for i in range(3))
            for x in range(w):
                px[x, y] = c
        tmp = cat / "_launch_gradient_tmp.png"
        img.save(tmp)
        _imageset(out, tmp, "LaunchGradient", scale="1x")
        tmp.unlink()
    return warns


def main() -> int:
    argv = sys.argv[1:]
    check_only = "--check" in argv
    if "--ios-repo" not in argv:
        print("error: --ios-repo <path to rostamvpn-ios> is required.\n"
              "       This tool writes into the iOS repo on purpose. Emitting into this\n"
              "       repo and trusting somebody to copy it is what shipped an empty\n"
              "       paywall once already.", file=sys.stderr)
        return 2
    ios_repo = pathlib.Path(argv[argv.index("--ios-repo") + 1]).expanduser().resolve()
    if not (ios_repo / "rostamvpn.xcodeproj").is_dir():
        print(f"error: {ios_repo} does not look like the iOS repo", file=sys.stderr)
        return 2
    skip = {"--check", "--ios-repo", str(ios_repo), argv[argv.index("--ios-repo") + 1]}
    args = [a for a in argv if a not in skip and not a.startswith("--")]
    manifests = {f.stem: json.loads(f.read_text())
                 for f in sorted(BRANDS.glob("*.json")) if f.name != "LOCKED.json"}
    wanted = args or sorted(manifests)
    written, skipped, warns, errors, drift = [], [], [], [], []
    for bid in wanted:
        m = manifests.get(bid)
        if m is None:
            print(f"  ERROR unknown brand {bid!r}", file=sys.stderr)
            return 2
        if not (m.get("ios") or {}).get("bundleId"):
            skipped.append(f"{bid}: no ios.bundleId -- not an iOS product yet")
            continue
        try:
            check(m, bid)
        except BrandError as e:
            errors.append(f"{bid}: {e}")
            continue
        d = ios_repo / "Brands" / bid
        files = {
            d / "Brand.xcconfig": gen_xcconfig(m, f"{bid}.json"),
            d / "BrandTheme.swift": gen_theme(m, f"{bid}.json"),
        }
        cfg_src = bundled_config_src(bid, m)
        cfg_dst = d / "default-config.json"
        if check_only:
            for path, body in files.items():
                if not path.exists() or path.read_text() != body:
                    drift.append(str(path.relative_to(ios_repo)))
            if cfg_src is None:
                if cfg_dst.exists():
                    drift.append(f"{cfg_dst.relative_to(ios_repo)} (stale: ios.bundleConfig is not set)")
            elif not cfg_dst.exists() or cfg_dst.read_bytes() != cfg_src.read_bytes():
                drift.append(str(cfg_dst.relative_to(ios_repo)))
            continue
        d.mkdir(parents=True, exist_ok=True)
        cat = d / "Brand.xcassets"
        cat.mkdir(exist_ok=True)
        (cat / "Contents.json").write_text(
            json.dumps({"info": {"author": "gen-ios.py", "version": 1}}, indent=2) + "\n")
        for path, body in files.items():
            path.write_text(body)
        cfg_dst.unlink(missing_ok=True)
        if cfg_src is not None:
            shutil.copyfile(cfg_src, cfg_dst)
        w = gen_icon(bid, cat)
        if w:
            warns.append(w)
        gen_dial_mark(bid, cat)
        warns.extend(gen_art(bid, m, cat))
        if (m.get("branding") or {}).get("hasMascot") and not (cat / "BrandDialMark.imageset").exists():
            warns.append(f"{bid}: branding.hasMascot is TRUE but "
                         f"Brands/{bid}/Brand.xcassets/BrandDialMark.imageset does not exist. "
                         f"The connect dial will draw NOTHING -- a blank ring, with no error. "
                         f"Add brands/assets/{bid}/dial-mark.svg (preferred) or dial-mark.png, "
                         f"on a square canvas whose aperture circle is 880/1040 of the width, "
                         f"or set branding.hasMascot false.")
        warns.extend(warnings(m, bid))
        written.append(bid)
    if check_only:
        if drift:
            print("error: generated files are stale, re-run gen-ios.py:", file=sys.stderr)
            for f in drift:
                print(f"  {f}", file=sys.stderr)
            return 1
        print("  generated iOS brand files are up to date")
        return 0
    for b in written:
        extra = (", default-config.json"
                 if (ios_repo / "Brands" / b / "default-config.json").exists() else "")
        print(f"  wrote {ios_repo.name}/Brands/{b}/  "
              f"(Brand.xcconfig, BrandTheme.swift, Brand.xcassets{extra})")
    for s in skipped:
        print(f"  skip  {s}")
    for w in warns:
        print(f"  WARNING {w}")
    for e in errors:
        print(f"  ERROR   {e}", file=sys.stderr)
    if written:
        print(f"\n  next: cd {ios_repo} && Scripts/select-brand.sh <brand>")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
